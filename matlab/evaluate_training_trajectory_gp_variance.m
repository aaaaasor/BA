function result = evaluate_training_trajectory_gp_variance( ...
    model_collection, training_times, training_x_slices, probe_count, ...
    output_dir, level_label)
%EVALUATE_TRAINING_TRAJECTORY_GP_VARIANCE GP variance on training paths.
% Select complete flow-matching trajectories (not isolated local-GP data
% point), evaluate every output variance only at the actual training-time
% samples, and save the summed raw variance and numerical summaries.

n_trajectories = size(training_x_slices, 2);
probe_count = min(max(1, round(probe_count)), n_trajectories);
trajectory_indices = unique(round(linspace(1, n_trajectories, ...
    probe_count)), 'stable');
probe_count = numel(trajectory_indices);

probe_times = training_times(:);
selected_training_paths = training_x_slices(:, trajectory_indices, :);
probe_paths = selected_training_paths;
variance_by_output = evaluate_rollout_uncertainty( ...
    model_collection, probe_times, probe_paths);
summed_variance = aggregate_variance_values(variance_by_output);

trajectory_min = min(summed_variance, [], 1)';
trajectory_median = median(summed_variance, 1)';
trajectory_mean = mean(summed_variance, 1)';
trajectory_max = max(summed_variance, [], 1)';
summary_table = table(trajectory_indices(:), trajectory_min, ...
    trajectory_median, trajectory_mean, trajectory_max, ...
    'VariableNames', {'training_trajectory_index', 'min_total_variance', ...
    'median_total_variance', 'mean_total_variance', ...
    'max_total_variance'});

fprintf(['%s training-trajectory summed GP variance over %d probes: ', ...
    'min/median/max = %.6g / %.6g / %.6g\n'], level_label, ...
    probe_count, min(summed_variance, [], 'all'), ...
    median(summed_variance, 'all'), max(summed_variance, [], 'all'));
disp(summary_table);

fig = figure('Color', 'w', 'WindowStyle', 'normal', ...
    'Units', 'normalized', 'Position', [0.16, 0.18, 0.60, 0.46]);
hold on;
colors = lines(probe_count);
for probe_idx = 1:probe_count
    if probe_count > 20
        line_color = [0.65, 0.78, 0.95];
        line_width = 0.55;
        visibility = 'off';
    else
        line_color = colors(probe_idx, :);
        line_width = 1.3;
        visibility = 'on';
    end
    plot(probe_times, summed_variance(:, probe_idx), '-', ...
        'Color', line_color, 'LineWidth', line_width, ...
        'HandleVisibility', visibility, ...
        'DisplayName', sprintf('training %d', ...
        trajectory_indices(probe_idx)));
end
if probe_count > 20
    plot(probe_times, median(summed_variance, 2), 'k-', ...
        'LineWidth', 2.0, 'DisplayName', 'median of all training curves');
end
grid on;
xlabel('t');
ylabel('\Sigma_i \sigma_i^2');
title(sprintf('%s: GP variance on %d training trajectories', ...
    level_label, probe_count), ...
    'Interpreter', 'none');
legend('Location', 'best', 'Interpreter', 'none');

if ~isfolder(output_dir)
    mkdir(output_dir);
end
base_name = [strrep(level_label, '-', '_'), ...
    '_training_trajectory_gp_variance'];
mat_path = fullfile(output_dir, [base_name, '.mat']);
csv_path = fullfile(output_dir, [base_name, '_summary.csv']);
png_path = fullfile(output_dir, [base_name, '.png']);
save(mat_path, 'training_times', 'probe_times', ...
    'trajectory_indices', 'probe_paths', 'variance_by_output', ...
    'summed_variance', 'summary_table');
writetable(summary_table, csv_path);
exportgraphics(fig, png_path, 'Resolution', 200);
fprintf('Saved training-trajectory GP variance: %s\n', png_path);

result = struct( ...
    'trajectory_indices', trajectory_indices(:), ...
    'training_times', training_times(:), ...
    'times', probe_times(:), ...
    'variance_by_output', variance_by_output, ...
    'summed_variance', summed_variance, ...
    'summary_table', summary_table, ...
    'mat_path', mat_path, ...
    'csv_path', csv_path, ...
    'png_path', png_path);
end
