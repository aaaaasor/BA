            'mode', 'endpoint_window_ard_length_scale_power', ...
            'endpoint_window_width', endpoint_window_width, ...
            'endpoint_power', ...
            third_segment_gp.length_scale_time_endpoint_power, ...
            'length_scale_cap', ...
            third_segment_gp.endpoint_length_scale_cap, ...
            'length_scale_floor', ...
            third_segment_gp.endpoint_length_scale_floor, ...
            'length_scale_start', ...
            third_segment_gp.length_scale_time_start_mat, ...
            'length_scale_end', ...
            third_segment_gp.length_scale_time_end_mat, ...
