                    'least one segment; regenerating its first-level seed ', ...
                    '(upstream attempt %d/%d).\n'], parent_idx, ...
                    second_seed_filter_cfg.max_attempts_per_trajectory, ...
                    upstream_round, max_second_upstream_retries);

