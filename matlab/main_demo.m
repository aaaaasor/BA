    third_segment_model_collection = fit_or_load_loggp_model( ...
        third_segment_s_slices, third_segment_x_slices, ...
        third_segment_y_slices, third_segment_gp, third_model_cache_path, ...
        'third-level');
    disp(['Third-level LoG-GP fit/load elapsed: ', ...
        num2str(toc(third_fit_timer), '%.1f'), ' seconds']);
    third_segment_model_collection = strip_model_for_prediction( ...
        third_segment_model_collection, 'Third-level');

    % 第三层是细化层：不拼接第二层各段，直接以第二层每段自己的 5 个
    % 点为参考，每个父段细分出 4 个第三层 segment（共 4x4=16 段），
    % PTCLF 只钉每个第三层 segment 的首尾两点（父段曲线的第 j / j+1
    % 点），中间 3 个点自由细化。相邻父段边界两侧的目标互不混合。
    % Third level refines one representative second-level curve per first-level
    % sample. The second level stores n_second_level_samples candidates for
    % each first-level curve; taking one from each group gives 5 * 16 = 80
    % third-level segments when first_level_generation_samples = 5.
    third_parent_eval_indices = 1:n_second_level_samples:n_second_level_eval;
    n_third_anchor_eval = numel(third_parent_eval_indices);
    third_parent_segment_rows = zeros( ...
        n_third_anchor_eval * n_generation_segments, 1);
    for third_anchor_idx = 1:n_third_anchor_eval
        source_eval_idx = third_parent_eval_indices(third_anchor_idx);
        source_rows = (source_eval_idx - 1) * n_generation_segments + ...
            (1:n_generation_segments);
        target_rows = (third_anchor_idx - 1) * n_generation_segments + ...
            (1:n_generation_segments);
        third_parent_segment_rows(target_rows) = source_rows;
    end
    third_parent_segment_data = final_segment_data(third_parent_segment_rows, :);
    n_third_generation_segments = n_generation_segments * ...
        (cfg.segment_points_per_segment - 1);
    n_third_samples = 1;
    n_third_level_eval = n_third_anchor_eval * n_third_samples;
    n_third_segment_eval = n_third_level_eval * n_third_generation_segments;
    n_third_segment_rows = segment_feature_dim * cfg.segment_points_per_segment;
    rng(cfg.second_level_rollout_seed + 100);
    third_segment_x_init = randn(n_third_segment_eval, n_third_segment_rows);

    disp('Running third-level segment RK4 rollout...');
    disp(['Third-level refinement samples: ', num2str(n_third_anchor_eval), ...
        ' parent curves x ', num2str(n_third_generation_segments), ...
        ' child segments = ', num2str(n_third_segment_eval), ...
        ' rollout samples.']);
    third_level_time_steps = cfg.first_level_time_steps;
    if isfield(cfg, 'third_level_time_steps') && ...
            ~isempty(cfg.third_level_time_steps)
        third_level_time_steps = cfg.third_level_time_steps;
    end
    third_level_rollout_t_max = cfg.rollout_t_max;
    % 与第二层一致：统一从 make_level_variance_constraint 构造约束
    % （含 slack 切换：t < switch 时 PTCLF 带 slack、HOCBF/PTCBF 硬，
    % 之后互换）。
    third_segment_variance_constraint = make_level_variance_constraint( ...
        cfg, 'third_level');
    % Third-level constraint ownership: PTCLF handles both endpoints, while
    % obstacle PTCBF acts only on the internal points of each five-point segment.
    third_internal_points = 2:(cfg.segment_points_per_segment - 1);
    if third_segment_variance_constraint.obstacle_enabled && ...
            ~isequal(sort(third_segment_variance_constraint.obstacle_points(:))', ...
            third_internal_points)
        error(['Third-level obstacle PTCBF must constrain only internal points ', ...
            '[%s]; endpoints are handled by PTCLF.'], ...
            num2str(third_internal_points));
    end
    % 目标同时供 PTCLF 约束和后面的端点误差诊断使用。
    [third_anchor_clf_targets, third_anchor_clf_matrix, ...
        third_anchor_clf_offset, third_anchor_clf_owner_std] = ...
        build_increment_endpoint_clf_targets( ...
        third_parent_segment_data, n_third_anchor_eval, n_third_samples, ...
        n_generation_segments, cfg.segment_points_per_segment, ...
        third_segment_data_transform);
    % 临时诊断: PTCLF 端点目标是否落在障碍内。目标落在障碍里时 PTCLF 与
    % PTCBF 互相矛盾(一个要求去、一个禁止进)，任何参数都修不了，必须先排除。
    % third_anchor_clf_targets 是未缩放的物理坐标(见下面的注释)。
    if isfield(cfg, 'obstacle') && struct_field_default(cfg.obstacle, 'enabled', false)
        obs_centers = cfg.obstacle.centers;
        endpoint_feature_dim = size(third_anchor_clf_targets, 2) / 2;
        disp('  [target-vs-obstacle check]');
        for endpoint_idx = 1:2
            target_xy = third_anchor_clf_targets(:, ...
                (endpoint_idx - 1) * endpoint_feature_dim + (1:2));
            for obs_idx = 1:size(obs_centers, 2)
                target_h = zeros(size(target_xy, 1), 1);
                for target_idx = 1:size(target_xy, 1)
                    target_h(target_idx) = obstacle_level_and_gradient( ...
                        target_xy(target_idx, :)', cfg.obstacle, obs_idx);
                end
                sorted_h = sort(target_h);
                fprintf(['    P%d vs obstacle %d: inside = %d / %d, ', ...
                    'h<0.5 = %d, 4 smallest h = %s\n'], ...
                    4 * endpoint_idx - 3, obs_idx, ...
                    sum(target_h < 0), numel(target_h), ...
                    sum(target_h < 0.5), ...
                    mat2str(sorted_h(1:min(4, numel(sorted_h)))', 6));
            end
        end
    end
    % Define the PTCLF error in standardized endpoint coordinates:
    %   e_z = D_owner^{-1} (M*z + offset - target).
    % P1 uses the first increment block's std and P5 uses the last block's
    % std, matching their sequential-QP ownership.  P5 remains a cumulative
    % physical endpoint map; this scaling changes only the CLF metric and
    % does not invent a blockwise target decomposition.  Keep the unscaled
    % physical map above for endpoint diagnostics and plotting.
    third_anchor_clf_error_scale = 1.0 ./ third_anchor_clf_owner_std(:);
    third_anchor_clf_targets_qp = third_anchor_clf_targets .* ...
        third_anchor_clf_error_scale';
    third_anchor_clf_matrix_qp = third_anchor_clf_matrix .* ...
        third_anchor_clf_error_scale;
    third_anchor_clf_offset_qp = third_anchor_clf_offset .* ...
        third_anchor_clf_error_scale;
    disp(['Third-level endpoint PTCLF uses owner-block standardized ', ...
        'position/tangent residuals.']);
    if third_segment_variance_constraint.ptclf_enabled
        third_segment_variance_constraint.anchor_clf_targets = ...
            third_anchor_clf_targets_qp;
        third_segment_variance_constraint.anchor_clf_matrix = ...
            third_anchor_clf_matrix_qp;
        third_segment_variance_constraint.anchor_clf_offset = ...
            third_anchor_clf_offset_qp;
    else
        % Endpoint replacement uses the physical map and targets directly;
        % no PTCLF metric scaling is involved in this ablation.
        third_segment_variance_constraint.anchor_clf_targets = ...
            third_anchor_clf_targets;
        third_segment_variance_constraint.anchor_clf_matrix = ...
            third_anchor_clf_matrix;
        third_segment_variance_constraint.anchor_clf_offset = ...
            third_anchor_clf_offset;
    end
    % The local increment cascade still owns the internal obstacle rows when
    % PTCLF is disabled, so its block metadata must not depend on PTCLF.
    sequential_increment_qp = struct_field_default( ...
        third_segment_variance_constraint, ...
        'sequential_increment_qp_enabled', false);
    if sequential_increment_qp
        third_segment_variance_constraint.increment_control_block_dim = ...
            segment_feature_dim;
        third_segment_variance_constraint.increment_control_block_count = ...
            cfg.segment_points_per_segment;
    end
    % 障碍 CBF: 第三层是局部增量表示，点->物理位置用累加矩阵映射(increment)，
    % 只约束每段内部点(端点被硬覆盖成已避障的 L2 点)。
    if third_segment_variance_constraint.obstacle_enabled
        third_segment_variance_constraint.obstacle_point_maps = ...
            build_obstacle_point_maps(third_segment_data_transform, ...
            segment_feature_dim, cfg.segment_points_per_segment, ...
            third_segment_variance_constraint.obstacle_points, 'increment');
    end
    if third_segment_variance_constraint.track_boundary_enabled
        third_segment_variance_constraint.track_boundary_point_maps = ...
            build_obstacle_point_maps(third_segment_data_transform, ...
            segment_feature_dim, cfg.segment_points_per_segment, ...
            third_segment_variance_constraint.track_boundary_points, ...
            'increment');
        [third_segment_variance_constraint.track_boundary_reference_s_min_targets, ...
            third_segment_variance_constraint.track_boundary_reference_s_max_targets] = ...
            build_track_boundary_reference_windows(n_third_segment_eval, ...
            n_third_generation_segments, cfg.segment_points_per_segment, ...
            third_segment_variance_constraint.track_boundary_points);
