            third_segment_gp.signal_std_vec(:).^2, eps), 1, 1, []);
        third_no_obstacle_normalized_variance = ...
            third_no_obstacle_uncertainty ./ third_sigma_f_squared;
        third_obstacle_normalized_variance = uncertainty_values ./ ...
            third_sigma_f_squared;
        n_third_variance_outputs = size(uncertainty_values, 3);
        third_no_obstacle_normalized_sigma = sqrt( ...
            aggregate_variance_values( ...
            third_no_obstacle_normalized_variance) ./ ...
            n_third_variance_outputs);
