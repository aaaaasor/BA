        'third_level_time_refine_start_t', ...
        cfg.second_level_time_refine_start_t);
    third_refine_extra_steps = struct_field_default(cfg, ...
        'third_level_time_refine_extra_steps', ...
        cfg.second_level_time_refine_extra_steps);
