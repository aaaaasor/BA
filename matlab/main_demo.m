            aggregate_variance_values( ...
            third_obstacle_normalized_variance) ./ ...
            n_third_variance_outputs);

        fig_third_obstacle_variance = figure('Name', ...
            'Third-level predictive variance before/after obstacle', ...
            'Color', 'w', 'WindowStyle', 'normal', ...
            'Units', 'normalized', ...
            'Position', [0.16, 0.20, 0.58, 0.46]);
        hold on;
        for sample_idx = 1:size( ...
                third_no_obstacle_normalized_sigma, 2)
            if sample_idx == 1
                baseline_visibility = 'on';
            else
                baseline_visibility = 'off';
            end
            plot(third_no_obstacle_rollout_times, ...
                third_no_obstacle_normalized_sigma(:, sample_idx), ...
                '--', 'Color', [0.45, 0.45, 0.45], ...
                'LineWidth', 1.0, ...
                'DisplayName', 'without obstacle PTCBF', ...
                'HandleVisibility', baseline_visibility);
        end
        for sample_idx = 1:size(third_obstacle_normalized_sigma, 2)
            if sample_idx == 1
                obstacle_visibility = 'on';
            else
                obstacle_visibility = 'off';
            end
            plot(third_rollout_times, ...
                third_obstacle_normalized_sigma(:, sample_idx), '-', ...
                'Color', [0.00, 0.45, 0.74], 'LineWidth', 1.2, ...
                'DisplayName', 'with obstacle PTCBF', ...
                'HandleVisibility', obstacle_visibility);
        end
        grid on;
        xlabel('s');
        ylabel(['normalized RMS uncertainty ', ...
            'sqrt(mean_i(\sigma_i^2 / \Sigma_{F,i}^2))']);
        title(['Third-level normalized predictive uncertainty: ', ...
            'before vs after obstacle PTCBF']);
        legend('Location', 'best');
        if cfg.output.enabled
            third_obstacle_variance_path = fullfile(this_dir, 'outputs', ...
                'ThirdLevel_Obstacle_BeforeAfter_Variance.emf');
            export_graphics_compat(fig_third_obstacle_variance, ...
                third_obstacle_variance_path);
            disp(['Saved third-level obstacle variance comparison: ', ...
                third_obstacle_variance_path]);
        end
    end
    uncertainty_times = third_rollout_times;
    uncertainty_level_label = 'third-level';
    uncertainty_integral_budget = third_segment_variance_constraint.integral_uncertainty_budget;
    if exist('third_rollout_diagnostics', 'var')
