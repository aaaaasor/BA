    % Per-output terminal PTCBF splits the scalar budget in proportion to
    % each output's prior variance, so it needs the fitted signal scales.
    third_segment_variance_constraint.signal_std_vec = ...
        third_segment_gp.signal_std_vec;
    % Include the kernel construction in the existing rollout-cache
    % comparison so switching between the old model and k0/k1 interpolation
    % cannot silently reuse trajectories generated by another GP.
    third_segment_variance_constraint.gp_kernel_signature = ...
        third_gp_kernel_signature;
    third_seed_filter_cfg = struct_field_default(cfg, ...
        'third_level_seed_filter', struct('enabled', false));
    if struct_field_default(third_seed_filter_cfg, 'enabled', false)
        target_valid_count = struct_field_default(third_seed_filter_cfg, ...
            'target_trajectory_count', n_third_level_eval);
        if n_third_level_eval ~= target_valid_count
            error(['Third-level seed filtering expects exactly %d parent ', ...
                'trajectories, but the current configuration creates %d.'], ...
                target_valid_count, n_third_level_eval);
        end
        third_initial_beta_bound = seed_filter_initial_variance_bound( ...
            third_segment_model_collection, third_seed_filter_cfg, ...
            n_third_level_eval, n_third_generation_segments, ...
            n_third_segment_rows, cfg.t_min);
        third_fixed_hbar0 = max(third_initial_beta_bound - ...
            third_segment_variance_constraint.terminal_variance_beta_final, ...
            0.0) + third_segment_variance_constraint. ...
            terminal_variance_ptzf_initial_margin;
        third_segment_variance_constraint. ...
            terminal_variance_ptzf_hbar0_fixed = third_fixed_hbar0;
        cfg.variance_constraint. ...
            third_level_terminal_variance_ptzf_hbar0_fixed = ...
            third_fixed_hbar0;
    end
    % Third-level constraint ownership: PTCLF handles both endpoints, while
    % obstacle PTCBF acts only on the internal points of each five-point segment.
    third_internal_points = 2:(cfg.segment_points_per_segment - 1);
    if third_segment_variance_constraint.obstacle_enabled && ...
            ~isequal(sort(third_segment_variance_constraint.obstacle_points(:))', ...
            third_internal_points)
        error(['Third-level obstacle PTCBF must constrain only internal points ', ...
            '[%s]; endpoints are handled by PTCLF.'], ...
            num2str(third_internal_points));
    end
    % 目标同时供 PTCLF 约束和后面的端点误差诊断使用。
    [third_anchor_clf_targets, third_anchor_clf_matrix, ...
        third_anchor_clf_offset, third_anchor_clf_owner_std] = ...
        build_increment_endpoint_clf_targets( ...
        third_parent_segment_data, n_third_anchor_eval, n_third_samples, ...
        n_generation_segments, cfg.segment_points_per_segment, ...
        third_segment_data_transform);
    % 临时诊断: PTCLF 端点目标是否落在障碍内。目标落在障碍里时 PTCLF 与
    % PTCBF 互相矛盾(一个要求去、一个禁止进)，任何参数都修不了，必须先排除。
    % third_anchor_clf_targets 是未缩放的物理坐标(见下面的注释)。
    if isfield(cfg, 'obstacle') && struct_field_default(cfg.obstacle, 'enabled', false)
        obs_centers = cfg.obstacle.centers;
        endpoint_feature_dim = size(third_anchor_clf_targets, 2) / 2;
        disp('  [target-vs-obstacle check]');
        for endpoint_idx = 1:2
            target_xy = third_anchor_clf_targets(:, ...
                (endpoint_idx - 1) * endpoint_feature_dim + (1:2));
            for obs_idx = 1:size(obs_centers, 2)
                target_h = zeros(size(target_xy, 1), 1);
                for target_idx = 1:size(target_xy, 1)
                    target_h(target_idx) = obstacle_level_and_gradient( ...
                        target_xy(target_idx, :)', cfg.obstacle, obs_idx);
                end
                sorted_h = sort(target_h);
                fprintf(['    P%d vs obstacle %d: inside = %d / %d, ', ...
                    'h<0.5 = %d, 4 smallest h = %s\n'], ...
                    4 * endpoint_idx - 3, obs_idx, ...
                    sum(target_h < 0), numel(target_h), ...
                    sum(target_h < 0.5), ...
                    mat2str(sorted_h(1:min(4, numel(sorted_h)))', 6));
            end
        end
    end
    % Define the PTCLF error in standardized endpoint coordinates:
    %   e_z = D_owner^{-1} (M*z + offset - target).
    % P1 uses the first increment block's std and P5 uses the last block's
    % std, matching their sequential-QP ownership.  P5 remains a cumulative
    % physical endpoint map; this scaling changes only the CLF metric and
    % does not invent a blockwise target decomposition.  Keep the unscaled
    % physical map above for endpoint diagnostics and plotting.
    third_anchor_clf_error_scale = 1.0 ./ third_anchor_clf_owner_std(:);
    third_anchor_clf_targets_qp = third_anchor_clf_targets .* ...
        third_anchor_clf_error_scale';
    third_anchor_clf_matrix_qp = third_anchor_clf_matrix .* ...
        third_anchor_clf_error_scale;
    third_anchor_clf_offset_qp = third_anchor_clf_offset .* ...
        third_anchor_clf_error_scale;
    if third_segment_variance_constraint.ptclf_enabled
        disp(['Third-level endpoint PTCLF uses owner-block standardized ', ...
            'position/tangent residuals.']);
        third_segment_variance_constraint.anchor_clf_targets = ...
            third_anchor_clf_targets_qp;
        third_segment_variance_constraint.anchor_clf_matrix = ...
            third_anchor_clf_matrix_qp;
        third_segment_variance_constraint.anchor_clf_offset = ...
            third_anchor_clf_offset_qp;
    else
        disp('Third-level endpoint PTCLF is disabled.');
        % Endpoint replacement uses the physical map and targets directly;
        % no PTCLF metric scaling is involved in this ablation.
        third_segment_variance_constraint.anchor_clf_targets = ...
            third_anchor_clf_targets;
        third_segment_variance_constraint.anchor_clf_matrix = ...
            third_anchor_clf_matrix;
        third_segment_variance_constraint.anchor_clf_offset = ...
            third_anchor_clf_offset;
    end
    % The local increment cascade still owns the internal obstacle rows when
    % PTCLF is disabled, so its block metadata must not depend on PTCLF.
    sequential_increment_qp = struct_field_default( ...
        third_segment_variance_constraint, ...
        'sequential_increment_qp_enabled', false);
    if sequential_increment_qp
        third_segment_variance_constraint.increment_control_block_dim = ...
            segment_feature_dim;
        third_segment_variance_constraint.increment_control_block_count = ...
            cfg.segment_points_per_segment;
    end
    % 障碍 CBF: 第三层是局部增量表示，点->物理位置用累加矩阵映射(increment)，
    % 只约束每段内部点(端点被硬覆盖成已避障的 L2 点)。
    if third_segment_variance_constraint.obstacle_enabled
        third_segment_variance_constraint.obstacle_point_maps = ...
            build_obstacle_point_maps(third_segment_data_transform, ...
            segment_feature_dim, cfg.segment_points_per_segment, ...
            third_segment_variance_constraint.obstacle_points, 'increment');
    end
    if third_segment_variance_constraint.track_boundary_enabled
        third_segment_variance_constraint.track_boundary_point_maps = ...
            build_obstacle_point_maps(third_segment_data_transform, ...
            segment_feature_dim, cfg.segment_points_per_segment, ...
            third_segment_variance_constraint.track_boundary_points, ...
            'increment');
        [third_segment_variance_constraint.track_boundary_reference_s_min_targets, ...
            third_segment_variance_constraint.track_boundary_reference_s_max_targets] = ...
            build_track_boundary_reference_windows(n_third_segment_eval, ...
            n_third_generation_segments, cfg.segment_points_per_segment, ...
            third_segment_variance_constraint.track_boundary_points);
    end
    if struct_field_default(cfg.output, ...
            'live_third_level_rk4_trajectory_enabled', false)
        live_parent_samples = struct_field_default(cfg.output, ...
            'live_third_level_rk4_trajectory_parent_samples', []);
        if isempty(live_parent_samples)
            live_parent_samples = 1:(n_third_segment_eval / ...
                n_third_generation_segments);
        end
        live_parent_samples = unique(round(live_parent_samples(:)'), ...
            'stable');
        n_third_parents = n_third_segment_eval / n_third_generation_segments;
        if any(live_parent_samples < 1 | ...
                live_parent_samples > n_third_parents)
            error(['Requested third-level live parent samples must lie ', ...
                'in [1, %d].'], n_third_parents);
        end
        live_third_sample_matrix = (live_parent_samples(:) - 1) .* ...
            n_third_generation_segments + ...
            (1:n_third_generation_segments);
        live_third_samples = reshape(live_third_sample_matrix.', 1, []);
        third_segment_variance_constraint.live_trajectory_plot_enabled = true;
        third_segment_variance_constraint.live_trajectory_plot_sample_indices = ...
            live_third_samples;
        third_segment_variance_constraint.live_trajectory_group_labels = ...
            live_parent_samples;
        third_segment_variance_constraint.live_trajectory_targets_first = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_trajectory_targets_first', true);
        third_segment_variance_constraint.live_trajectory_alternating_segment_colors = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_alternating_segment_colors', false);
        third_segment_variance_constraint.live_trajectory_group_size = ...
            n_third_generation_segments;
        third_segment_variance_constraint.live_trajectory_plot_stride = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_trajectory_stride', 1);
        third_segment_variance_constraint.live_trajectory_plot_delay = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_trajectory_delay', 0.0);
        third_segment_variance_constraint.live_trajectory_close_after_save = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_trajectory_close_after_save', false);
        third_segment_variance_constraint.live_trajectory_track_segment = ...
            cfg.track_segment;
        third_segment_variance_constraint.live_trajectory_save_enabled = 0;
        third_segment_variance_constraint.live_trajectory_accumulate_segments = true;
        third_segment_variance_constraint.live_trajectory_level_label = ...
            'Third-level';
        third_segment_variance_constraint.live_trajectory_video_enabled = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_video_enabled', false);
        third_segment_variance_constraint.live_trajectory_video_frame_rate = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_video_frame_rate', 20);
        third_segment_variance_constraint.live_trajectory_video_quality = ...
            struct_field_default(cfg.output, ...
            'live_third_level_rk4_video_quality', 95);
        third_segment_variance_constraint.live_trajectory_video_output_pattern = ...
            fullfile(this_dir, 'outputs', ...
            'ThirdLevel_RK4_Trajectory_%03d.mp4');
        % Obstacle rows own only P2/P3/P4, but the live curve must display
        % all five physical points of each child segment.
        third_segment_variance_constraint.live_trajectory_point_maps = ...
            build_obstacle_point_maps(third_segment_data_transform, ...
            segment_feature_dim, cfg.segment_points_per_segment, ...
            1:cfg.segment_points_per_segment, 'increment');
    end
    % Use the same refined integration grid for the obstacle rollout and
    % its no-obstacle baseline. The only changed QP setting is
    % obstacle_enabled.
    third_refine_start_t = struct_field_default(cfg, ...
        'third_level_time_refine_start_t', ...
        cfg.second_level_time_refine_start_t);
    third_refine_extra_steps = struct_field_default(cfg, ...
        'third_level_time_refine_extra_steps', ...
        cfg.second_level_time_refine_extra_steps);
    third_level_refine_cfg = struct( ...
        'base_steps', third_level_time_steps, ...
        'start_t', third_refine_start_t, ...
        'extra_steps', third_refine_extra_steps);
    third_rollout_cache_path = fullfile(this_dir, cfg.cache.third_level_rollout_path);
    third_rollout_cache_dir = fileparts(third_rollout_cache_path);
    if ~exist(third_rollout_cache_dir, 'dir'); mkdir(third_rollout_cache_dir); end
    use_third_rollout_cache = false;
    if isfile(third_rollout_cache_path)
        cached = load(third_rollout_cache_path);
        if size(cached.third_traj_path_10d, 2) == n_third_segment_eval
            needs_third_terminal_diagnostics = struct_field_default( ...
                third_segment_variance_constraint, ...
                'ptcbf_enabled', false);
            needs_third_trace_diagnostics = struct_field_default( ...
                third_segment_variance_constraint, ...
                'diagnostics', false);
            needs_third_control_trace = struct_field_default( ...
                third_segment_variance_constraint, ...
                'control_trace_enabled', false);
            cache_has_third_diagnostics = isfield(cached, ...
                'third_rollout_diagnostics') && ...
                isfield(cached.third_rollout_diagnostics, 'hocbf') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_terminal_inequality_h') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_terminal_bound') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_integral_bound') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_terminal_ptzf_initial_bound');
            cache_has_third_state_traces = cache_has_third_diagnostics && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_x') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_mu') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_v') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_obstacle_min_grad_ctrl_norm') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_anchor_clf_first_raw_residual') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_anchor_clf_last_raw_residual') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_anchor_clf_last_effective_bound') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_anchor_clf_last_owner_grad_norm') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_u_ptclf_reference') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_u_after_ptcbf') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_stage_hocbf_residual_after_ptcbf') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_u_hocbf_correction');
            cache_has_third_u_trace = isfield(cached, ...
                'third_rollout_diagnostics') && ...
                isfield(cached.third_rollout_diagnostics, 'hocbf') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, 'trace_u') && ...
                ~isempty(cached.third_rollout_diagnostics.hocbf.trace_u);
            cache_requests_u_only = struct_field_default( ...
                third_segment_variance_constraint, ...
                'control_trace_u_only', false);
            cache_has_third_full_control_trace = ...
                isfield(cached.third_rollout_diagnostics.hocbf, 'trace_mu') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, 'trace_v') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_u_ptclf_reference') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_u_ptcbf_correction') && ...
                isfield(cached.third_rollout_diagnostics.hocbf, ...
                'trace_u_hocbf_correction');
            cache_has_third_control_trace = cache_has_third_u_trace && ...
                (cache_requests_u_only || cache_has_third_full_control_trace);
            % 尾段加密配置(start_t/extra_steps)不属于约束结构体，单独存一份
            % 一起比较，否则只改这两个参数不会让缓存失效、rollout 不会重跑。
            cache_matches_third_refine_cfg = isfield(cached, ...
                'saved_third_level_refine_cfg') && ...
                isequaln(cached.saved_third_level_refine_cfg, ...
                third_level_refine_cfg);
            cache_matches_third_constraint = isfield(cached, ...
                'saved_third_segment_variance_constraint') && ...
                isequaln(cached.saved_third_segment_variance_constraint, ...
                third_segment_variance_constraint) && ...
                cache_matches_third_refine_cfg;
            third_seed_filter_enabled = struct_field_default( ...
                third_seed_filter_cfg, 'enabled', false);
            cache_matches_third_seed_filter = isfield(cached, ...
                'saved_third_level_seed_filter') && ...
                isequaln(cached.saved_third_level_seed_filter, ...
                third_seed_filter_cfg) && ...
                isfield(cached, 'accepted_third_level_seeds') && ...
                isequal(size(cached.accepted_third_level_seeds), ...
                [n_third_level_eval, n_third_generation_segments]) && ...
                isfield(cached, 'third_level_seed_acceptance') && ...
                isfield(cached, 'accepted_third_level_uncertainty') && ...
                isfield(cached, 'third_segment_x_init');
            if (~needs_third_terminal_diagnostics || ...
                    cache_has_third_diagnostics) && ...
                    (~needs_third_trace_diagnostics || ...
                    cache_has_third_state_traces) && ...
                    (~needs_third_control_trace || ...
                    cache_has_third_control_trace) && ...
                    cache_matches_third_constraint && ...
                    cache_matches_third_seed_filter
                third_rollout_times = cached.third_rollout_times;
                third_traj_path_10d = cached.third_traj_path_10d;
                if cache_has_third_diagnostics || ...
                        cache_has_third_control_trace
                    third_rollout_diagnostics = cached.third_rollout_diagnostics;
                end
                third_segment_x_init = cached.third_segment_x_init;
                accepted_third_level_seeds = ...
                    cached.accepted_third_level_seeds;
                third_level_seed_acceptance = ...
                    cached.third_level_seed_acceptance;
                accepted_third_level_uncertainty = ...
                    cached.accepted_third_level_uncertainty;
                use_third_rollout_cache = true;
                disp(['Loaded cached third-level rollout: ', third_rollout_cache_path]);
            elseif ~cache_matches_third_constraint
                disp(['Ignoring third-level rollout cache because rollout ', ...
                    'constraint config changed.']);
            elseif ~cache_matches_third_seed_filter
                disp(['Ignoring third-level rollout cache because rollout ', ...
                    'seed filter changed.']);
            else
                disp(['Ignoring third-level rollout cache without required ', ...
                    'state/control diagnostics.']);
            end
        else
            disp(['Ignoring third-level rollout cache with sample count ', ...
                num2str(size(cached.third_traj_path_10d, 2)), ...
                '; expected ', num2str(n_third_segment_eval), '.']);
        end
    end
    if ~use_third_rollout_cache
        third_rollout_timer = tic;
        % 在 PTZF 包络急剧收紧的尾段加密时间步。第三层可用独立的加密
        % 配置(更密的尾段步),避免牵连第二层;未配置时回退到第二层的值。
        if struct_field_default(third_seed_filter_cfg, 'enabled', false)
            third_seed_filter_runtime = third_seed_filter_cfg;
            third_seed_filter_runtime.return_on_exhaustion = true;
            [third_rollout_times, third_traj_path_10d, ...
                third_rollout_diagnostics, third_segment_x_init, ...
                accepted_third_level_seeds, ...
                third_level_seed_acceptance, ...
                accepted_third_level_uncertainty, third_exhaustion] = ...
                generate_valid_second_level_rollouts( ...
                third_segment_model_collection, ...
                third_segment_variance_constraint, n_third_level_eval, ...
                n_third_generation_segments, n_third_segment_rows, ...
                cfg.segment_points_per_segment, ...
                third_segment_data_transform, cfg.t_min, ...
                third_level_rollout_t_max, third_level_time_steps, ...
                third_level_refine_cfg, cfg.parallel, ...
                third_seed_filter_runtime);

            % L3 backoff is one level at a time. Four L3 child segments are
            % owned by one L2 segment. After any child exhausts its 20 local
            % seeds, regenerate that L2 owner and then rerun only its four
            % children. If the L2 owner itself exhausts 20 seeds, escalate
            % once more and regenerate the owning L1 parent plus all L2/L3
            % descendants.
            third_to_second_retry_counts = zeros( ...
                n_third_level_eval, n_generation_segments);
            third_to_first_retry_counts = zeros(n_third_level_eval, 1);
            hierarchy_modified_first = false;
            hierarchy_modified_second = false;
            max_third_upstream_retries = struct_field_default( ...
                third_seed_filter_cfg, 'max_upstream_retries', 10);
            exhausted_owner_pairs = unique([ ...
                third_exhaustion.parent_indices(:), ...
                ceil(third_exhaustion.segment_indices(:) ./ ...
                (cfg.segment_points_per_segment - 1))], 'rows', 'stable');
            while ~isempty(exhausted_owner_pairs)
                third_parent_idx = exhausted_owner_pairs(1, 1);
                l2_owner_segment = exhausted_owner_pairs(1, 2);
                exhausted_owner_pairs(1, :) = [];
                owner_complete = false;
                while ~owner_complete
                    third_to_second_retry_counts( ...
                        third_parent_idx, l2_owner_segment) = ...
                        third_to_second_retry_counts( ...
                        third_parent_idx, l2_owner_segment) + 1;
                    l2_retry_round = third_to_second_retry_counts( ...
                        third_parent_idx, l2_owner_segment);
                    if l2_retry_round > max_third_upstream_retries
                        third_to_second_retry_counts( ...
                            third_parent_idx, l2_owner_segment) = ...
                            max_third_upstream_retries;
                        fprintf(['  L3 children remained infeasible after ', ...
                            '%d replacement L2 segments; escalating to ', ...
                            'the owning L1 parent.\n'], ...
                            max_third_upstream_retries);
                        break;
                    end
                    fprintf(['Third-level parent %d segment group %d ', ...
                        'exhausted local seeds; regenerating its owning ', ...
                        'second-level segment (%d/%d).\n'], ...
                        third_parent_idx, l2_owner_segment, l2_retry_round, ...
                        max_third_upstream_retries);

                    second_parent_idx = third_parent_eval_indices( ...
                        third_parent_idx);
                    global_l2_row = (second_parent_idx - 1) * ...
                        n_generation_segments + l2_owner_segment;
                    l2_filter = second_seed_filter_cfg;
                    l2_filter.target_trajectory_count = 1;
                    l2_filter.parallel_trajectory_batch_size = 1;
                    l2_filter.return_on_exhaustion = true;
                    l2_initial_reserve = n_second_level_eval * ...
                        second_seed_filter_cfg.max_attempts_per_trajectory * ...
                        n_generation_segments;
                    l2_lineage_idx = ((third_parent_idx - 1) * ...
                        n_generation_segments + l2_owner_segment - 1) * ...
                        max_third_upstream_retries + l2_retry_round - 1;
                    l2_filter.base_seed = double( ...
                        second_seed_filter_cfg.base_seed) + l2_initial_reserve + ...
                        1000000 + l2_lineage_idx * ...
                        second_seed_filter_cfg.max_attempts_per_trajectory;
                    l2_constraint = subset_rollout_rows( ...
                        segment_rollout_constraint, global_l2_row);
                    [l2_times, l2_path, l2_diag, l2_x_init, l2_seeds, ...
                        l2_acceptance, l2_uncertainty, l2_exhaustion] = ...
                        generate_valid_second_level_rollouts( ...
                        segment_model_collection, l2_constraint, 1, 1, ...
                        n_segment_rows, cfg.segment_points_per_segment, ...
                        segment_data_transform, cfg.t_min, cfg.rollout_t_max, ...
                        cfg.second_level_time_steps, second_level_refine_cfg, ...
                        cfg.parallel, l2_filter);
                    rollout_diagnostics = replace_rollout_diagnostics_samples( ...
                        rollout_diagnostics, l2_diag, global_l2_row);
                    if l2_exhaustion.occurred
                        % This fixed L1 parent cannot supply a feasible L2
                        % owner after 20 seeds. Regenerate the complete parent
                        % hierarchy below instead of trying another local L2
                        % cycle against the same anchors.
                        break;
                    end
                    if ~isequal(l2_times, segment_rollout_times)
                        error('L2 fallback produced a different time grid.');
                    end
                    segment_traj_path_10d(:, global_l2_row, :) = l2_path;
                    for local_time_idx = 1:numel(l2_times)
                        local_state = reshape(l2_path(local_time_idx, 1, :), ...
                            1, []);
                        local_physical_state = local_state .* ...
                            segment_data_transform.std' + ...
                            segment_data_transform.mean';
                        segment_traj_path_plot(local_time_idx, ...
                            global_l2_row, :) = reshape( ...
                            local_physical_state, 1, 1, []);
                    end
                    segment_x_init(global_l2_row, :) = l2_x_init;
                    accepted_second_level_seeds( ...
                        second_parent_idx, l2_owner_segment) = l2_seeds;
                    accepted_second_level_uncertainty(:, global_l2_row, :) = ...
                        l2_uncertainty;
                    second_level_seed_acceptance = ...
                        replace_seed_acceptance_segment( ...
                        second_level_seed_acceptance, second_parent_idx, ...
                        l2_owner_segment, l2_acceptance);
                    hierarchy_modified_second = true;
                    l2_final_std = reshape(l2_path(end, 1, :), 1, []);
                    final_segment_data(global_l2_row, :) = l2_final_std .* ...
                        segment_data_transform.std' + ...
                        segment_data_transform.mean';

                    [third_segment_variance_constraint, ...
                        third_anchor_clf_targets, third_anchor_clf_matrix, ...
                        third_anchor_clf_offset, third_anchor_clf_owner_std, ...
                        third_parent_segment_data] = ...
                        refresh_third_level_anchor_constraint( ...
                        third_segment_variance_constraint, final_segment_data, ...
                        third_parent_segment_rows, n_third_anchor_eval, ...
                        n_generation_segments, cfg.segment_points_per_segment, ...
                        third_segment_data_transform);

                    child_segments = (l2_owner_segment - 1) * ...
                        (cfg.segment_points_per_segment - 1) + ...
                        (1:(cfg.segment_points_per_segment - 1));
                    global_l3_rows = (third_parent_idx - 1) * ...
                        n_third_generation_segments + child_segments;
                    l3_filter = third_seed_filter_cfg;
                    l3_filter.target_trajectory_count = 1;
                    l3_filter.parallel_trajectory_batch_size = 1;
                    l3_filter.return_on_exhaustion = true;
                    l3_initial_reserve = n_third_level_eval * ...
                        third_seed_filter_cfg.max_attempts_per_trajectory * ...
                        n_third_generation_segments;
                    l3_lineage_idx = ((third_parent_idx - 1) * ...
                        n_generation_segments + l2_owner_segment - 1) * ...
                        max_third_upstream_retries + l2_retry_round - 1;
                    l3_filter.base_seed = double( ...
                        third_seed_filter_cfg.base_seed) + l3_initial_reserve + ...
                        l3_lineage_idx * ...
                        third_seed_filter_cfg.max_attempts_per_trajectory * ...
                        numel(child_segments);
                    l3_constraint = subset_rollout_rows( ...
                        third_segment_variance_constraint, global_l3_rows);
                    [l3_times, l3_path, l3_diag, l3_x_init, l3_seeds, ...
                        l3_acceptance, l3_uncertainty, l3_exhaustion] = ...
                        generate_valid_second_level_rollouts( ...
                        third_segment_model_collection, l3_constraint, 1, ...
                        numel(child_segments), n_third_segment_rows, ...
                        cfg.segment_points_per_segment, ...
                        third_segment_data_transform, cfg.t_min, ...
                        third_level_rollout_t_max, third_level_time_steps, ...
                        third_level_refine_cfg, cfg.parallel, l3_filter);
                    third_rollout_diagnostics = ...
                        replace_rollout_diagnostics_samples( ...
                        third_rollout_diagnostics, l3_diag, global_l3_rows);
                    if l3_exhaustion.occurred
                        fprintf(['  replacement L2 segment passed, but one ', ...
                            'of its four L3 children again exhausted; ', ...
                            'trying the next L2 seed lineage.\n']);
                        continue;
                    end
                    if ~isequal(l3_times, third_rollout_times)
                        error('L3 fallback produced a different time grid.');
                    end
                    third_traj_path_10d(:, global_l3_rows, :) = l3_path;
                    third_segment_x_init(global_l3_rows, :) = l3_x_init;
                    accepted_third_level_seeds( ...
                        third_parent_idx, child_segments) = l3_seeds;
                    accepted_third_level_uncertainty(:, global_l3_rows, :) = ...
                        l3_uncertainty;
                    third_level_seed_acceptance = ...
                        replace_seed_acceptance_segment_block( ...
                        third_level_seed_acceptance, third_parent_idx, ...
                        child_segments, l3_acceptance);
                    owner_complete = true;
                end

                if ~owner_complete
                    % The owning L2 segment itself exhausted. Escalate to a
                    % fresh L1 parent; all four L2 and all sixteen L3
                    % descendants of this parent are then invalidated.
                    hierarchy_ctx = struct( ...
                        'first_filter', first_seed_filter_cfg, ...
                        'first_constraint', first_rollout_constraint, ...
                        'first_model', model_collection, ...
                        'first_transform', data_transform, ...
                        'first_state_dim', n_rows, ...
                        'first_point_count', n_points_first, ...
                        'first_feature_dim', first_level_feature_dim, ...
                        'first_time_steps', cfg.first_level_time_steps, ...
                        'n_first_parents', n_eval, ...
                        'second_filter', second_seed_filter_cfg, ...
                        'second_constraint', segment_rollout_constraint, ...
                        'second_model', segment_model_collection, ...
                        'second_transform', segment_data_transform, ...
                        'second_state_dim', n_segment_rows, ...
                        'second_time_steps', cfg.second_level_time_steps, ...
                        'second_refine', second_level_refine_cfg, ...
                        'second_anchor_points', second_level_anchor_points, ...
                        'n_second_samples', n_second_level_samples, ...
                        'n_second_segments', n_generation_segments, ...
                        'n_second_parents', n_second_level_eval, ...
                        'points_per_segment', cfg.segment_points_per_segment, ...
                        't_min', cfg.t_min, 't_max', cfg.rollout_t_max, ...
                        'parallel', cfg.parallel, ...
                        'max_upstream_retries', max_third_upstream_retries, ...
                        'seed_namespace', 20000);
                    hierarchy_complete = false;
                    while ~hierarchy_complete
                        third_to_first_retry_counts(third_parent_idx) = ...
                            third_to_first_retry_counts(third_parent_idx) + 1;
                        l1_retry_round = third_to_first_retry_counts( ...
                            third_parent_idx);
                        if l1_retry_round > max_third_upstream_retries
                            error(['Third-level parent %d exceeded %d complete ', ...
                                'L1 hierarchy regenerations.'], ...
                                third_parent_idx, max_third_upstream_retries);
                        end
                        fprintf(['  L2 owner also exhausted; regenerating ', ...
                            'L1 parent %d and all four L2 segments ', ...
                            '(%d/%d).\n'], second_parent_idx, l1_retry_round, ...
                            max_third_upstream_retries);
                        hierarchy_result = regenerate_hierarchy_parent( ...
                            hierarchy_ctx, second_parent_idx, l1_retry_round);
                        hierarchy_complete = ...
                            ~hierarchy_result.second_exhaustion.occurred;
                    end
                    % Commit the regenerated L1 and all four regenerated L2
                    % segments, then rebuild all sixteen L3 descendants.
                    traj_path_10d(:, second_parent_idx, :) = ...
                        hierarchy_result.first_path;
                    x_init(second_parent_idx, :) = hierarchy_result.first_x_init;
                    accepted_first_level_seeds(second_parent_idx, :) = ...
                        hierarchy_result.first_seeds;
                    accepted_first_level_uncertainty(:, second_parent_idx, :) = ...
                        hierarchy_result.first_uncertainty;
                    first_level_seed_acceptance = replace_seed_acceptance_parent( ...
                        first_level_seed_acceptance, second_parent_idx, ...
                        hierarchy_result.first_acceptance);
                    first_rollout_diagnostics = ...
                        replace_rollout_diagnostics_samples( ...
                        first_rollout_diagnostics, ...
                        hierarchy_result.first_diagnostics, second_parent_idx);
                    reconstructed_points(:, second_parent_idx, :) = ...
                        hierarchy_result.first_points;
                    final_trajectory_data(second_parent_idx, :) = ...
                        hierarchy_result.first_final_physical;
                    for local_time_idx = 1:numel(hierarchy_result.first_times)
                        local_state = reshape(hierarchy_result.first_path( ...
                            local_time_idx, 1, :), 1, []);
                        local_physical_state = local_state .* ...
                            data_transform.std' + data_transform.mean';
                        traj_path_plot(local_time_idx, second_parent_idx, :) = ...
                            reshape(local_physical_state, 1, 1, []);
                    end
                    second_level_anchor_points = ...
                        hierarchy_result.second_anchor_points;
                    segment_rollout_constraint = ...
                        hierarchy_result.second_constraint;
                    l2_parent_rows = (second_parent_idx - 1) * ...
                        n_generation_segments + (1:n_generation_segments);
                    segment_traj_path_10d(:, l2_parent_rows, :) = ...
                        hierarchy_result.second_path;
                    for local_time_idx = 1:numel(hierarchy_result.second_times)
                        local_states = reshape(hierarchy_result.second_path( ...
                            local_time_idx, :, :), n_generation_segments, []);
                        local_physical_states = local_states .* ...
                            segment_data_transform.std' + ...
                            segment_data_transform.mean';
                        segment_traj_path_plot(local_time_idx, ...
                            l2_parent_rows, :) = reshape(local_physical_states, ...
                            1, n_generation_segments, []);
                    end
                    segment_x_init(l2_parent_rows, :) = ...
                        hierarchy_result.second_x_init;
                    accepted_second_level_seeds(second_parent_idx, :) = ...
                        hierarchy_result.second_seeds;
                    accepted_second_level_uncertainty(:, l2_parent_rows, :) = ...
                        hierarchy_result.second_uncertainty;
                    second_level_seed_acceptance = replace_seed_acceptance_parent( ...
                        second_level_seed_acceptance, second_parent_idx, ...
                        hierarchy_result.second_acceptance);
                    rollout_diagnostics = ...
                        replace_rollout_diagnostics_samples( ...
                        rollout_diagnostics, ...
                        hierarchy_result.second_diagnostics, l2_parent_rows);
                    for local_l2_idx = 1:n_generation_segments
                        row_now = l2_parent_rows(local_l2_idx);
                        state_now = reshape(hierarchy_result.second_path( ...
                            end, local_l2_idx, :), 1, []);
                        final_segment_data(row_now, :) = state_now .* ...
                            segment_data_transform.std' + ...
                            segment_data_transform.mean';
                    end
                    [third_segment_variance_constraint, ...
                        third_anchor_clf_targets, third_anchor_clf_matrix, ...
                        third_anchor_clf_offset, third_anchor_clf_owner_std, ...
                        third_parent_segment_data] = ...
                        refresh_third_level_anchor_constraint( ...
                        third_segment_variance_constraint, final_segment_data, ...
                        third_parent_segment_rows, n_third_anchor_eval, ...
                        n_generation_segments, cfg.segment_points_per_segment, ...
                        third_segment_data_transform);

                    % A changed L1 parent invalidates all sixteen L3
                    % descendants. Rebuild them once against the freshly
                    % generated four L2 segments. Only an owner whose child
                    % still exhausts its 20 attempts is queued for another
                    % L2-local regeneration.
                    all_child_segments = 1:n_third_generation_segments;
                    all_l3_rows = (third_parent_idx - 1) * ...
                        n_third_generation_segments + all_child_segments;
                    all_l3_filter = third_seed_filter_cfg;
                    all_l3_filter.target_trajectory_count = 1;
                    all_l3_filter.parallel_trajectory_batch_size = 1;
                    all_l3_filter.return_on_exhaustion = true;
                    all_l3_initial_reserve = n_third_level_eval * ...
                        third_seed_filter_cfg.max_attempts_per_trajectory * ...
                        n_third_generation_segments;
                    all_l3_filter.base_seed = double( ...
                        third_seed_filter_cfg.base_seed) + ...
                        all_l3_initial_reserve + 2000000 + ...
                        ((third_parent_idx - 1) * max_third_upstream_retries + ...
                        l1_retry_round - 1) * ...
                        third_seed_filter_cfg.max_attempts_per_trajectory * ...
                        n_third_generation_segments;
                    all_l3_constraint = subset_rollout_rows( ...
                        third_segment_variance_constraint, all_l3_rows);
                    [all_l3_times, all_l3_path, all_l3_diag, all_l3_x_init, ...
                        all_l3_seeds, all_l3_acceptance, all_l3_uncertainty, ...
                        all_l3_exhaustion] = ...
                        generate_valid_second_level_rollouts( ...
                        third_segment_model_collection, all_l3_constraint, 1, ...
                        n_third_generation_segments, n_third_segment_rows, ...
                        cfg.segment_points_per_segment, ...
                        third_segment_data_transform, cfg.t_min, ...
                        third_level_rollout_t_max, third_level_time_steps, ...
                        third_level_refine_cfg, cfg.parallel, all_l3_filter);
                    if ~isequal(all_l3_times, third_rollout_times)
                        error('Full L3 hierarchy retry produced a different time grid.');
                    end
                    third_rollout_diagnostics = ...
                        replace_rollout_diagnostics_samples( ...
                        third_rollout_diagnostics, all_l3_diag, all_l3_rows);
                    all_l3_valid = all(isfinite(all_l3_seeds), 1);
                    valid_l3_segments = find(all_l3_valid);
                    valid_l3_rows = all_l3_rows(valid_l3_segments);
                    if ~isempty(valid_l3_segments)
                        third_traj_path_10d(:, valid_l3_rows, :) = ...
                            all_l3_path(:, valid_l3_segments, :);
                        third_segment_x_init(valid_l3_rows, :) = ...
                            all_l3_x_init(valid_l3_segments, :);
                        accepted_third_level_uncertainty(:, valid_l3_rows, :) = ...
                            all_l3_uncertainty(:, valid_l3_segments, :);
                    end
                    accepted_third_level_seeds(third_parent_idx, :) = ...
                        all_l3_seeds;
                    third_level_seed_acceptance = ...
                        replace_seed_acceptance_segment_block( ...
                        third_level_seed_acceptance, third_parent_idx, ...
                        all_child_segments, all_l3_acceptance);

                    % Remove stale owner entries for this parent. The fresh
                    % full-child pass determines which owners, if any, need
                    % another local L2 regeneration.
                    exhausted_owner_pairs( ...
                        exhausted_owner_pairs(:, 1) == third_parent_idx, :) = [];
                    third_to_second_retry_counts(third_parent_idx, :) = 0;
                    failed_l3_owners = unique(ceil( ...
                        all_l3_exhaustion.segment_indices(:) ./ ...
                        (cfg.segment_points_per_segment - 1)), 'stable');
                    if ~isempty(failed_l3_owners)
                        exhausted_owner_pairs = [ ...
                            [repmat(third_parent_idx, ...
                            numel(failed_l3_owners), 1), failed_l3_owners]; ...
                            exhausted_owner_pairs]; %#ok<AGROW>
                    end
                    hierarchy_modified_first = true;
                    hierarchy_modified_second = true;
                end
            end
            third_level_seed_acceptance.upstream_second_retry_counts = ...
                third_to_second_retry_counts;
            third_level_seed_acceptance.upstream_first_retry_counts = ...
                third_to_first_retry_counts;
            third_level_seed_acceptance.upstream_retry_policy = ...
                ['exhausted L3 child -> regenerate owning L2 segment; ', ...
                'exhausted L2 owner -> regenerate owning L1 parent'];
            third_level_seed_acceptance.accepted_count = n_third_level_eval;
            third_level_seed_acceptance.accepted_segment_count = ...
                n_third_segment_eval;
            if hierarchy_modified_first
                saved_first_rollout_constraint = first_rollout_constraint;
                saved_first_level_seed_filter = first_seed_filter_cfg;
                save(first_rollout_cache_path, 'rollout_times', ...
                    'traj_path_10d', 'first_rollout_diagnostics', ...
                    'saved_first_rollout_constraint', 'x_init', ...
                    'accepted_first_level_seeds', ...
                    'first_level_seed_acceptance', ...
                    'accepted_first_level_uncertainty', ...
                    'saved_first_level_seed_filter', 'data_transform', '-v7.3');
                save(first_seed_mat_path, 'accepted_first_level_seeds', ...
                    'first_level_seed_acceptance');
            end
            if hierarchy_modified_second
                saved_segment_rollout_constraint = segment_rollout_constraint;
                saved_second_level_seed_filter = second_seed_filter_cfg;
                save(segment_rollout_cache_path, 'segment_rollout_times', ...
                    'segment_traj_path_10d', 'rollout_diagnostics', ...
                    'segment_x_init', 'accepted_second_level_seeds', ...
                    'second_level_seed_acceptance', ...
                    'accepted_second_level_uncertainty', ...
                    'saved_segment_rollout_constraint', ...
                    'saved_second_level_seed_filter', ...
                    'segment_data_transform', '-v7.3');
                save(seed_mat_path, 'accepted_second_level_seeds', ...
                    'second_level_seed_acceptance');
            end
        else
            % Advisor seed layout: every child segment owns one seed. Rows
            % are complete parent trajectories and columns are their 16
            % third-level segments.
            accepted_third_level_seeds = reshape( ...
                double(cfg.third_level_rollout_seed) + ...
                (0:(n_third_segment_eval - 1)), ...
                n_third_generation_segments, n_third_level_eval)';
            third_segment_x_init = ...
                build_second_level_initial_states_from_seeds( ...
                accepted_third_level_seeds, ...
                n_third_generation_segments, n_third_segment_rows);
            [third_rollout_times, third_traj_path_10d, ...
                third_rollout_diagnostics] = rk4_rollout( ...
                third_segment_model_collection, third_segment_x_init, ...
                cfg.t_min, third_level_rollout_t_max, ...
                third_level_time_steps, third_segment_variance_constraint, ...
                third_level_refine_cfg, cfg.parallel);
            third_level_seed_acceptance = struct( ...
                'enabled', false, 'seed_scope', 'segment');
            accepted_third_level_uncertainty = [];
        end
        disp(['Third-level RK4 rollout elapsed: ', ...
            num2str(toc(third_rollout_timer), '%.1f'), ' seconds']);
        saved_third_segment_variance_constraint = ...
            third_segment_variance_constraint;
        saved_third_level_refine_cfg = third_level_refine_cfg;
        saved_third_level_seed_filter = third_seed_filter_cfg;
        try
            save(third_rollout_cache_path, 'third_rollout_times', ...
                'third_traj_path_10d', 'third_rollout_diagnostics', ...
                'third_segment_x_init', 'accepted_third_level_seeds', ...
                'third_level_seed_acceptance', ...
                'accepted_third_level_uncertainty', ...
                'saved_third_segment_variance_constraint', ...
                'saved_third_level_refine_cfg', ...
                'saved_third_level_seed_filter', ...
                'third_segment_data_transform');
        catch
            save(third_rollout_cache_path, 'third_rollout_times', ...
                'third_traj_path_10d', 'third_rollout_diagnostics', ...
                'third_segment_x_init', 'accepted_third_level_seeds', ...
                'third_level_seed_acceptance', ...
                'accepted_third_level_uncertainty', ...
                'saved_third_segment_variance_constraint', ...
                'saved_third_level_refine_cfg', ...
                'saved_third_level_seed_filter', ...
                'third_segment_data_transform', '-v7.3');
        end
        disp(['Saved cached third-level rollout: ', third_rollout_cache_path]);
    end

    % Always export the per-segment layout, even when rejection filtering is
    % disabled, so every delivered segment can be reproduced independently.
    third_seed_trajectory_idx = repelem((1:n_third_level_eval)', ...
        n_third_generation_segments);
    third_seed_segment_idx = repmat( ...
        (1:n_third_generation_segments)', n_third_level_eval, 1);
    third_seed_table = table(third_seed_trajectory_idx, ...
        third_seed_segment_idx, ...
        reshape(accepted_third_level_seeds', [], 1), ...
        'VariableNames', {'trajectory_index', 'segment_index', 'seed'});
    if struct_field_default(third_level_seed_acceptance, 'enabled', false)
        repeat_segment_metric = @(values) repelem(values(:), ...
            n_third_generation_segments);
        third_seed_table.attempt_count = repeat_segment_metric( ...
            third_level_seed_acceptance.attempt_counts);
        third_seed_table.max_variance_excess = repeat_segment_metric( ...
            third_level_seed_acceptance.final_max_excess);
        third_seed_table.min_variance_margin = repeat_segment_metric( ...
            third_level_seed_acceptance.final_min_margin);
        third_seed_table.min_hocbf_psi0 = repeat_segment_metric( ...
            third_level_seed_acceptance.final_min_hocbf_psi0);
        third_seed_table.min_hocbf_psi1 = repeat_segment_metric( ...
            third_level_seed_acceptance.final_min_hocbf_psi1);
        third_seed_table.min_track_point_h = repeat_segment_metric( ...
            third_level_seed_acceptance.final_min_track_point_h);
        third_seed_table.min_obstacle_point_h = repeat_segment_metric( ...
            third_level_seed_acceptance.final_min_obstacle_point_h);
        if isfield(third_level_seed_acceptance, 'segment_attempt_counts')
            third_seed_table.attempt_count = reshape( ...
                third_level_seed_acceptance.segment_attempt_counts', [], 1);
            third_seed_table.segment_max_variance_excess = reshape( ...
                third_level_seed_acceptance.segment_final_max_excess', [], 1);
        end
    end
    third_seed_csv_path = fullfile(this_dir, 'outputs', ...
        'third_level_segment_seeds.csv');
    writetable(third_seed_table, third_seed_csv_path);
    third_seed_mat_path = fullfile(this_dir, 'outputs', ...
        'third_level_segment_seeds.mat');
    save(third_seed_mat_path, 'accepted_third_level_seeds', ...
        'third_level_seed_acceptance');
    disp(['Saved reproducible per-segment third-level seeds: ', ...
        third_seed_csv_path]);

    % Generate the requested HOCBF psi1, HOCBF psi2, and terminal PTCBF h
    % time traces without enabling full diagnostics for all third-level
    % samples.  The selected sample is re-run serially with the same model,
    % initial state, constraints, time grid, and refinement configuration.
    if struct_field_default(cfg, ...
            'third_level_cbf_trace_plot_enabled', true)
        cbf_trace_sample_idx = struct_field_default(cfg, ...
            'third_level_cbf_trace_sample_idx', 4);
        try
            plot_cbf_time_traces_for_sample(cfg, ...
                third_segment_model_collection, third_segment_x_init, ...
                cfg.t_min, third_level_rollout_t_max, ...
                third_level_time_steps, third_segment_variance_constraint, ...
                third_level_refine_cfg, cbf_trace_sample_idx);
        catch cbf_trace_error
            warning('main_demo:CBFTracePlotFailed', ...
                'Could not generate HOCBF/PTCBF time traces: %s', ...
                cbf_trace_error.message);
        end
    end

    % Third-level before/after experiment. Both runs inherit the exact same
    % safe second-level anchors, increment initial state, HOCBF, PTCLF,
    % integration grid, and random seed. Only obstacle PTCBF is disabled in
    % the baseline.
    third_no_obstacle_traj_path_10d = [];
    third_no_obstacle_rollout_times = [];
    if third_segment_variance_constraint.obstacle_enabled && ...
            struct_field_default(cfg, 'third_level_run_no_obstacle_baseline', true)
        third_no_obstacle_constraint = third_segment_variance_constraint;
        third_no_obstacle_constraint.obstacle_enabled = false;
        third_no_obstacle_constraint.control_trace_enabled = false;
        third_no_obstacle_cache_path = fullfile(this_dir, ...
            cfg.cache.third_level_no_obstacle_rollout_path);
        third_no_obstacle_cache_dir = fileparts( ...
            third_no_obstacle_cache_path);
        if ~exist(third_no_obstacle_cache_dir, 'dir')
            mkdir(third_no_obstacle_cache_dir);
        end

        use_third_no_obstacle_cache = false;
        if isfile(third_no_obstacle_cache_path)
            third_no_obstacle_cached = load(third_no_obstacle_cache_path);
            third_no_obstacle_cache_has_fields = isfield( ...
                third_no_obstacle_cached, ...
                'third_no_obstacle_traj_path_10d') && isfield( ...
                third_no_obstacle_cached, ...
                'third_no_obstacle_rollout_times');
            if third_no_obstacle_cache_has_fields && ...
                    size(third_no_obstacle_cached. ...
                    third_no_obstacle_traj_path_10d, 2) == ...
                    n_third_segment_eval && size( ...
                    third_no_obstacle_cached. ...
                    third_no_obstacle_traj_path_10d, 3) == ...
                    n_third_segment_rows
                third_no_obstacle_constraint_matches = isfield( ...
                    third_no_obstacle_cached, ...
                    'saved_third_no_obstacle_constraint') && ...
                    isequaln(third_no_obstacle_cached. ...
                    saved_third_no_obstacle_constraint, ...
                    third_no_obstacle_constraint);
                third_no_obstacle_seed_matches = isfield( ...
                    third_no_obstacle_cached, ...
                    'saved_third_no_obstacle_rollout_seeds') && ...
                    isequaln(third_no_obstacle_cached. ...
                    saved_third_no_obstacle_rollout_seeds, ...
                    accepted_third_level_seeds);
                if third_no_obstacle_constraint_matches && ...
                        third_no_obstacle_seed_matches
                    third_no_obstacle_traj_path_10d = ...
                        third_no_obstacle_cached. ...
                        third_no_obstacle_traj_path_10d;
                    third_no_obstacle_rollout_times = ...
                        third_no_obstacle_cached. ...
                        third_no_obstacle_rollout_times;
                    use_third_no_obstacle_cache = true;
                    disp(['Loaded cached third-level no-obstacle ', ...
                        'rollout: ', third_no_obstacle_cache_path]);
                end
            end
        end

        if ~use_third_no_obstacle_cache
            disp(['Running third-level no-obstacle baseline rollout ', ...
                'for before/after comparison...']);
            third_no_obstacle_timer = tic;
            [third_no_obstacle_rollout_times, ...
                third_no_obstacle_traj_path_10d] = rk4_rollout( ...
                third_segment_model_collection, third_segment_x_init, ...
                cfg.t_min, third_level_rollout_t_max, ...
                third_level_time_steps, third_no_obstacle_constraint, ...
                third_level_refine_cfg, cfg.parallel);
            disp(['Third-level no-obstacle baseline elapsed: ', ...
                num2str(toc(third_no_obstacle_timer), '%.1f'), ...
                ' seconds']);
            saved_third_no_obstacle_constraint = ...
                third_no_obstacle_constraint;
