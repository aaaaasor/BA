clear;
clc;
% close all;
%% Configuration
cfg = get_config();
% Legacy/global reproducibility for data preparation only.  Second-level
% generated trajectories do not consume this stream: each complete
% trajectory owns an explicit RandStream seed and can be replayed alone.
rng(cfg.random_seed);

%% Training Data
disp('Building first-level trajectory-space training data...');
this_file = mfilename('fullpath');
this_dir = fileparts(this_file);
[first_level_target_points, track_segment] = scenario_training_points( ...
    cfg, 5, cfg.n_train);

if ~isempty(track_segment)
    cfg.track_segment = track_segment;
    if strcmpi(struct_field_default(cfg, 'scenario', ''), 'racing') && ...
            struct_field_default(cfg.obstacle, 'enabled', false)
        cfg.obstacle = configure_racing_obstacles(track_segment, cfg.obstacle);
        plot_racing_obstacle_layout(cfg);
    end
    if isfield(cfg, 'track_boundary') && ...
            struct_field_default(cfg.track_boundary, 'enabled', false)
        cfg.track_boundary.geometry = build_track_boundary_geometry( ...
            track_segment, struct_field_default(cfg.track_boundary, ...
            'n_spline_points', 400), ...
            struct_field_default(cfg.track_boundary, 'spline_type', 'spline'));
        if struct_field_default(cfg.output, 'plot_pchip_vs_raw_track', false)
            plot_pchip_vs_real_track(cfg);
        end
        if struct_field_default(cfg.output, ...
                'plot_first_level_joint_softmin_safe_set', false)
            plot_first_level_joint_softmin_safe_set(cfg);
        end
    end
end
if isfield(cfg, 'first_level_use_tangent_features') && ...
        ~cfg.first_level_use_tangent_features
    first_level_target_points = first_level_target_points(:, :, 1:2);
    cfg.cache.first_level_model_path = fullfile('outputs', ...
        'LoG_GP_FirstLevel_PositionOnly_Model.mat');
    cfg.cache.first_level_rollout_path = fullfile('outputs', ...
        'LoG_GP_FirstLevel_PositionOnly_Rollout_WithHOCBF_PTCBF.mat');
    cfg.cache.first_level_hyperparameter_path = fullfile('outputs', ...
        'LoG_GP_FirstLevel_PositionOnly_Hyperparameter.mat');
    first_level_feature_mode = 'position only [x, y]';
else
    first_level_feature_mode = '[x, y, dx/ds, dy/ds] tangent';
end
disp(['Scenario: ', cfg.scenario]);
disp(['First-level target source: 5-point trajectories with ', ...
    first_level_feature_mode, ' features']);
rng(cfg.first_level_data_seed);
[s_slices, x_slices, y_slices, target_points, source_points, ...
    target_data, source_data, trajectory_t_slices, data_transform] = build_training_data( ...
    cfg.t_min, 1.0, cfg.n_time_slices, first_level_target_points);
first_level_feature_dim = size(target_points, 3);

%% LoG-GP Hyperparameters
% 第一层使用 cfg.gp 的独立副本，避免把第一层专用的运行时字段
% （样本级索引、超参数等）写回公共模板、泄漏给后续层。
disp('Optimizing or loading first-level LoG-GP hyperparameters...');
rng(cfg.first_level_hyperparameter_seed);
first_gp = cfg.gp;
first_gp.o_ratio = cfg.gp.first_level_o_ratio;
first_gp.hyperparameter_mat_path = cfg.cache.first_level_hyperparameter_path;
first_gp.n_pretrain = cfg.gp.first_level_n_pretrain;
first_gp = optimize_gp_hyperparameters(x_slices, y_slices, first_gp, s_slices);

%% Fit LoG-GP Flow Model
first_gp.training_accuracy_threshold = ...
    cfg.gp.first_level_training_accuracy_threshold;
disp('Fitting first-level LoG-GP flow model...');
rng(cfg.first_level_fit_seed);
first_model_cache_path = fullfile(this_dir, cfg.cache.first_level_model_path);
first_fit_timer = tic;
model_collection = fit_or_load_loggp_model(s_slices, x_slices, y_slices, ...
    first_gp, first_model_cache_path, 'first-level');
disp(['First-level LoG-GP fit/load elapsed: ', ...
    num2str(toc(first_fit_timer), '%.1f'), ' seconds']);
% 拟合/加载完成后丢掉 K：后面只做预测，不再往模型里加数据。K 与 L 同样大，
% 而 parfor 要把整个模型广播给每一个 worker，丢掉它直接把传输量减半。
model_collection = strip_model_for_prediction(model_collection, 'First-level');

%% RK4 Rollout
disp('Running first-level RK4 rollout...');
n_rows = size(source_data, 1);
n_eval = cfg.first_level_generation_samples;
first_rollout_cache_path = fullfile(this_dir, cfg.cache.first_level_rollout_path);
first_rollout_cache_dir = fileparts(first_rollout_cache_path);
if ~exist(first_rollout_cache_dir, 'dir'); mkdir(first_rollout_cache_dir); end
first_rollout_constraint = make_level_variance_constraint(cfg, 'first_level');
first_seed_filter_cfg = struct_field_default(cfg, ...
    'first_level_seed_filter', struct('enabled', false));
if struct_field_default(first_seed_filter_cfg, 'enabled', false)
    target_valid_count = struct_field_default(first_seed_filter_cfg, ...
        'target_trajectory_count', n_eval);
    if n_eval ~= target_valid_count
        error(['First-level seed filtering expects exactly %d ', ...
            'trajectories, but first_level_generation_samples is %d.'], ...
            target_valid_count, n_eval);
    end
    % Use one model-derived envelope for every retry batch so acceptance is
    % independent of when a candidate seed happens to be evaluated.
    first_initial_beta_bound = seed_filter_initial_variance_bound( ...
        model_collection, first_seed_filter_cfg, n_eval, 1, n_rows, ...
        cfg.t_min);
    fixed_hbar0 = max(first_initial_beta_bound - ...
        first_rollout_constraint.terminal_variance_beta_final, 0.0) + ...
        first_rollout_constraint.terminal_variance_ptzf_initial_margin;
    first_rollout_constraint.terminal_variance_ptzf_hbar0_fixed = fixed_hbar0;
    cfg.variance_constraint.first_level_terminal_variance_ptzf_hbar0_fixed = ...
        fixed_hbar0;
end

if first_rollout_constraint.obstacle_enabled
    n_points_first = n_rows / first_level_feature_dim;
    first_rollout_constraint.obstacle_point_maps = build_obstacle_point_maps( ...
        data_transform, first_level_feature_dim, n_points_first, ...
        first_rollout_constraint.obstacle_points, 'absolute');
end
if first_rollout_constraint.track_boundary_enabled
    n_points_first = n_rows / first_level_feature_dim;
    first_rollout_constraint.track_boundary_point_maps = ...
        build_obstacle_point_maps(data_transform, first_level_feature_dim, ...
        n_points_first, first_rollout_constraint.track_boundary_points, ...
        'absolute');
    [first_rollout_constraint.track_boundary_reference_s_min_targets, ...
        first_rollout_constraint.track_boundary_reference_s_max_targets] = ...
        build_track_boundary_reference_windows(n_eval, 1, n_points_first, ...
        first_rollout_constraint.track_boundary_points);
end
if struct_field_default(cfg.output, ...
        'live_first_level_rk4_trajectory_enabled', false)
    first_rollout_constraint.live_trajectory_plot_enabled = true;
    first_rollout_constraint.live_trajectory_plot_sample_indices = ...
        struct_field_default(cfg.output, ...
        'live_first_level_rk4_trajectory_sample_indices', 1);
    first_rollout_constraint.live_trajectory_plot_stride = ...
        struct_field_default(cfg.output, ...
        'live_first_level_rk4_trajectory_stride', 1);
    first_rollout_constraint.live_trajectory_plot_delay = ...
        struct_field_default(cfg.output, ...
        'live_first_level_rk4_trajectory_delay', 0.0);
    first_rollout_constraint.live_trajectory_close_after_save = ...
        struct_field_default(cfg.output, ...
        'live_first_level_rk4_trajectory_close_after_save', false);
    first_rollout_constraint.live_trajectory_track_segment = cfg.track_segment;
    first_rollout_constraint.live_trajectory_save_enabled = cfg.output.enabled;
end
use_first_rollout_cache = false;
if isfile(first_rollout_cache_path)
    cached = load(first_rollout_cache_path);
    if size(cached.traj_path_10d, 2) == n_eval
        cache_has_diagnostics = isfield(cached, 'first_rollout_diagnostics') && ...
            isfield(cached.first_rollout_diagnostics, 'hocbf');
        cache_matches_constraint = isfield(cached, ...
            'saved_first_rollout_constraint') && ...
            isequaln(cached.saved_first_rollout_constraint, ...
            first_rollout_constraint);
        first_seed_filter_enabled = struct_field_default( ...
            first_seed_filter_cfg, 'enabled', false);
        cache_has_valid_seed_layout = isfield(cached, ...
            'accepted_first_level_seeds') && ...
            ((first_seed_filter_enabled && ...
            numel(cached.accepted_first_level_seeds) == n_eval) || ...
            (~first_seed_filter_enabled && ...
            isscalar(cached.accepted_first_level_seeds) && ...
            isequaln(cached.accepted_first_level_seeds, ...
            cfg.first_level_rollout_seed)));
        cache_matches_seed_filter = isfield(cached, ...
            'saved_first_level_seed_filter') && ...
            isequaln(cached.saved_first_level_seed_filter, ...
            first_seed_filter_cfg) && ...
            cache_has_valid_seed_layout && ...
            isfield(cached, 'first_level_seed_acceptance') && ...
            isfield(cached, 'accepted_first_level_uncertainty') && ...
            isfield(cached, 'x_init');
        if cache_has_diagnostics && cache_matches_constraint && ...
                cache_matches_seed_filter
            rollout_times = cached.rollout_times;
            traj_path_10d = cached.traj_path_10d;
            first_rollout_diagnostics = cached.first_rollout_diagnostics;
            x_init = cached.x_init;
            accepted_first_level_seeds = cached.accepted_first_level_seeds;
            first_level_seed_acceptance = ...
                cached.first_level_seed_acceptance;
            accepted_first_level_uncertainty = ...
                cached.accepted_first_level_uncertainty;
            use_first_rollout_cache = true;
            disp(['Loaded cached first-level rollout: ', first_rollout_cache_path]);
        elseif ~cache_matches_constraint
            disp(['Ignoring first-level rollout cache because rollout ', ...
                'constraint config changed.']);
        elseif ~cache_matches_seed_filter
            disp(['Ignoring first-level rollout cache because rollout ', ...
                'seed filter changed.']);
        else
            disp(['Ignoring first-level rollout cache without HOCBF/PTCBF ', ...
                'diagnostics.']);
        end
    else
        disp(['Ignoring first-level rollout cache with sample count ', ...
            num2str(size(cached.traj_path_10d, 2)), ...
            '; expected ', num2str(n_eval), '.']);
    end
end
if ~use_first_rollout_cache
    first_rollout_timer = tic;
    if struct_field_default(first_seed_filter_cfg, 'enabled', false)
        n_points_first = n_rows / first_level_feature_dim;
        [rollout_times, traj_path_10d, first_rollout_diagnostics, ...
            x_init, accepted_first_level_seeds, ...
            first_level_seed_acceptance, ...
            accepted_first_level_uncertainty] = ...
            generate_valid_second_level_rollouts(model_collection, ...
            first_rollout_constraint, n_eval, 1, n_rows, n_points_first, ...
            data_transform, cfg.t_min, cfg.rollout_t_max, ...
            cfg.first_level_time_steps, [], cfg.parallel, ...
            first_seed_filter_cfg);
    else
        rng(cfg.first_level_rollout_seed);
        x_init = randn(n_eval, n_rows);
        [rollout_times, traj_path_10d, first_rollout_diagnostics] = ...
            rk4_rollout(model_collection, x_init, cfg.t_min, ...
            cfg.rollout_t_max, cfg.first_level_time_steps, ...
            first_rollout_constraint, [], cfg.parallel);
        accepted_first_level_seeds = cfg.first_level_rollout_seed;
        first_level_seed_acceptance = struct('enabled', false);
        accepted_first_level_uncertainty = [];
    end
    disp(['First-level RK4 rollout elapsed: ', ...
        num2str(toc(first_rollout_timer), '%.1f'), ' seconds']);
    saved_first_rollout_constraint = first_rollout_constraint;
    saved_first_level_seed_filter = first_seed_filter_cfg;
    try
        % data_transform 一并存下: rollout 里的状态是归一化坐标, 缺了它就无法
        % 离线把缓存还原成物理坐标做几何检查(走廊内外、障碍缝、越界量)。
        save(first_rollout_cache_path, 'rollout_times', 'traj_path_10d', ...
            'first_rollout_diagnostics', 'saved_first_rollout_constraint', ...
            'x_init', 'accepted_first_level_seeds', ...
            'first_level_seed_acceptance', ...
            'accepted_first_level_uncertainty', ...
            'saved_first_level_seed_filter', 'data_transform');
    catch
        save(first_rollout_cache_path, 'rollout_times', 'traj_path_10d', ...
            'first_rollout_diagnostics', 'saved_first_rollout_constraint', ...
            'x_init', 'accepted_first_level_seeds', ...
            'first_level_seed_acceptance', ...
            'accepted_first_level_uncertainty', ...
            'saved_first_level_seed_filter', 'data_transform', '-v7.3');
    end
    disp(['Saved cached first-level rollout: ', first_rollout_cache_path]);
end

if struct_field_default(first_level_seed_acceptance, 'enabled', false)
    first_seed_table = table((1:n_eval)', accepted_first_level_seeds(:), ...
        first_level_seed_acceptance.attempt_counts(:), ...
        first_level_seed_acceptance.final_max_excess(:), ...
        first_level_seed_acceptance.final_min_margin(:), ...
        first_level_seed_acceptance.final_min_hocbf_psi0(:), ...
        first_level_seed_acceptance.final_min_hocbf_psi1(:), ...
        first_level_seed_acceptance.final_min_track_point_h(:), ...
        first_level_seed_acceptance.final_min_obstacle_point_h(:), ...
        'VariableNames', {'trajectory_index', 'seed', 'attempt_count', ...
        'max_variance_excess', 'min_variance_margin', ...
        'min_hocbf_psi0', 'min_hocbf_psi1', 'min_track_point_h', ...
        'min_obstacle_point_h'});
    first_seed_csv_path = fullfile(this_dir, 'outputs', ...
        'first_level_accepted_trajectory_seeds.csv');
    writetable(first_seed_table, first_seed_csv_path);
    first_seed_mat_path = fullfile(this_dir, 'outputs', ...
        'first_level_accepted_trajectory_seeds.mat');
    save(first_seed_mat_path, 'accepted_first_level_seeds', ...
        'first_level_seed_acceptance');
    disp(['Saved 100 reproducible accepted first-level trajectory seeds: ', ...
        first_seed_csv_path]);
end

% Matched first-level no-obstacle baseline. Keep the initial states, GP,
% HOCBF, terminal variance PTCBF, time grid, and every other constraint
% setting identical; disable only the obstacle CBF. Cache it separately so
% plotting the before/after comparison does not double every later run.
first_no_obstacle_traj_path_10d = [];
first_no_obstacle_rollout_times = [];
run_first_no_obstacle_baseline = struct_field_default( ...
    cfg, 'first_level_run_no_obstacle_baseline', false);
if run_first_no_obstacle_baseline && ...
        first_rollout_constraint.obstacle_enabled
    first_no_obstacle_constraint = first_rollout_constraint;
    first_no_obstacle_constraint.obstacle_enabled = false;
    first_no_obstacle_cache_path = fullfile(this_dir, ...
        cfg.cache.first_level_no_obstacle_rollout_path);
    first_no_obstacle_cache_dir = fileparts( ...
        first_no_obstacle_cache_path);
    if ~exist(first_no_obstacle_cache_dir, 'dir')
        mkdir(first_no_obstacle_cache_dir);
    end

    use_first_no_obstacle_cache = false;
    if isfile(first_no_obstacle_cache_path)
        first_no_obstacle_cached = load(first_no_obstacle_cache_path);
        cache_has_expected_fields = isfield(first_no_obstacle_cached, ...
            'first_no_obstacle_traj_path_10d') && ...
            isfield(first_no_obstacle_cached, ...
            'first_no_obstacle_rollout_times');
        if cache_has_expected_fields && ...
                size(first_no_obstacle_cached. ...
                first_no_obstacle_traj_path_10d, 2) == n_eval && ...
                size(first_no_obstacle_cached. ...
                first_no_obstacle_traj_path_10d, 3) == n_rows
            cache_matches_constraint = isfield(first_no_obstacle_cached, ...
                'saved_first_no_obstacle_constraint') && ...
                isequaln(first_no_obstacle_cached. ...
                saved_first_no_obstacle_constraint, ...
                first_no_obstacle_constraint);
            cache_matches_seed = isfield(first_no_obstacle_cached, ...
                'saved_first_no_obstacle_rollout_seeds') && ...
                isequaln(first_no_obstacle_cached. ...
                saved_first_no_obstacle_rollout_seeds, ...
                accepted_first_level_seeds);
            if cache_matches_constraint && cache_matches_seed
                first_no_obstacle_traj_path_10d = ...
                    first_no_obstacle_cached. ...
                    first_no_obstacle_traj_path_10d;
                first_no_obstacle_rollout_times = ...
                    first_no_obstacle_cached. ...
                    first_no_obstacle_rollout_times;
                use_first_no_obstacle_cache = true;
                disp(['Loaded cached first-level no-obstacle rollout: ', ...
                    first_no_obstacle_cache_path]);
            end
        end
    end

    if ~use_first_no_obstacle_cache
        disp(['Running first-level no-obstacle baseline rollout ', ...
            'for before/after comparison...']);
        first_no_obstacle_timer = tic;
        [first_no_obstacle_rollout_times, ...
            first_no_obstacle_traj_path_10d] = rk4_rollout( ...
            model_collection, x_init, cfg.t_min, cfg.rollout_t_max, ...
            cfg.first_level_time_steps, first_no_obstacle_constraint, ...
            [], cfg.parallel);
        disp(['First-level no-obstacle baseline elapsed: ', ...
            num2str(toc(first_no_obstacle_timer), '%.1f'), ' seconds']);
        saved_first_no_obstacle_constraint = ...
            first_no_obstacle_constraint;
        saved_first_no_obstacle_rollout_seeds = ...
            accepted_first_level_seeds;
        try
            save(first_no_obstacle_cache_path, ...
                'first_no_obstacle_rollout_times', ...
                'first_no_obstacle_traj_path_10d', ...
                'saved_first_no_obstacle_constraint', ...
                'saved_first_no_obstacle_rollout_seeds');
        catch
            save(first_no_obstacle_cache_path, ...
                'first_no_obstacle_rollout_times', ...
                'first_no_obstacle_traj_path_10d', ...
                'saved_first_no_obstacle_constraint', ...
                'saved_first_no_obstacle_rollout_seeds', '-v7.3');
        end
        disp(['Saved first-level no-obstacle baseline: ', ...
            first_no_obstacle_cache_path]);
    end
end

traj_path_plot = zeros(size(traj_path_10d));
for time_idx = 1:numel(rollout_times)
