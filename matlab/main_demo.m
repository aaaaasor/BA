        disp(['Optimizing or loading third-level full-domain ', ...
            'hyperparameters...']);
        rng(cfg.second_level_hyperparameter_seed + 100);
        third_segment_gp = optimize_gp_hyperparameters( ...
            third_segment_x_slices, third_segment_y_slices, ...
