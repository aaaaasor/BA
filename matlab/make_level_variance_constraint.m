function level_constraint = make_level_variance_constraint(cfg, level_prefix)
level_constraint = struct();

level_constraint.integral_uncertainty_budget = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_integral_uncertainty_budget']);
level_constraint.hocbf_enabled = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_hocbf_enabled']);
level_constraint.hocbf_alpha2 = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_hocbf_alpha2']);
level_constraint.hocbf_relaxation_bound = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_hocbf_relaxation_bound']);
level_constraint.psi1_margin = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_psi1_margin']);
level_constraint.diagnostics = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_diagnostics']);
level_constraint.ptcbf_enabled = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_ptcbf_enabled']);
level_constraint.terminal_variance_beta_final = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_terminal_variance_beta_final']);
level_constraint.terminal_variance_ptzf_initial_margin = struct_field_required( ...
    cfg.variance_constraint, ...
    [level_prefix, '_terminal_variance_ptzf_initial_margin']);
level_constraint.terminal_variance_ptzf_gamma = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_terminal_variance_ptzf_gamma']);
level_constraint.terminal_variance_alpha = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_terminal_variance_alpha']);
level_constraint.ptclf_enabled = struct_field_required( ...
    cfg.variance_constraint, [level_prefix, '_ptclf_enabled']);
level_constraint.anchor_clf_ptzf_enabled = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_clf_ptzf_enabled'], true);
level_constraint.anchor_clf_ptzf_cg = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_clf_ptzf_cg'], 0.1);
level_constraint.anchor_clf_cpt = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_clf_cpt'], 1.0);
level_constraint.anchor_clf_ptzf_initial_margin = struct_field_default( ...
    cfg.variance_constraint, ...
    [level_prefix, '_anchor_clf_ptzf_initial_margin'], 1e-6);
level_constraint.slack_enabled = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_slack_enabled'], true);
level_constraint.hocbf_slack_enabled = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_hocbf_slack_enabled'], ...
    level_constraint.slack_enabled);
level_constraint.terminal_variance_slack_enabled = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_terminal_variance_slack_enabled'], ...
    level_constraint.slack_enabled);
% 统一的 slack 切换时刻: t < switch 时 PTCLF 带 slack、HOCBF/PTCBF 硬；
% t >= switch 后互换(PTCLF 变硬，HOCBF/PTCBF 开 slack)。默认 inf 即不切换。
slack_switch_time = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_slack_switch_time'], inf);
level_constraint.terminal_variance_slack_late_start_time = slack_switch_time;
level_constraint.hocbf_slack_late_start_time = slack_switch_time;
level_constraint.anchor_clf_slack_hard_after_time = slack_switch_time;
level_constraint.anchor_clf_slack_enabled = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_clf_slack_enabled'], ...
    level_constraint.slack_enabled);
level_constraint.anchor_clf_slack_weight = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_clf_slack_weight'], 1e4);
level_constraint.hocbf_slack_weight = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_hocbf_slack_weight'], ...
    level_constraint.anchor_clf_slack_weight);
level_constraint.terminal_variance_slack_weight = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_terminal_variance_slack_weight'], ...
    level_constraint.anchor_clf_slack_weight);
% 端点 snap-and-hold: 倒数这么多步时把首尾点钉成上层生成点并保持固定，
% 之后纯 flow matching 抹平段边界折角。0 表示关闭（保持旧行为）。
level_constraint.anchor_snap_flow_steps = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_snap_flow_steps'], 0);
% 对照实验开关: true 时 snap 只覆盖位置(x,y)，不覆盖斜率(dx/ds,dy/ds)。
level_constraint.anchor_snap_position_only = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_snap_position_only'], false);
% 对照实验开关: true 时 PTCLF 全程只约束位置(x,y)，不约束斜率
% (dx/ds,dy/ds)。在 main_demo.m 里对 anchor_clf_indices/targets 生效。
level_constraint.anchor_clf_position_only = struct_field_default( ...
    cfg.variance_constraint, [level_prefix, '_anchor_clf_position_only'], false);
level_constraint.grad_tol = cfg.variance_constraint.grad_tol;

% 障碍 CBF（避障）。总开关 cfg.obstacle.enabled 与该层开关同时为真才生效。
% 几何/blow-up/slack 参数从 cfg.obstacle 读取；点->物理位置映射
% (obstacle_point_maps) 需要 data_transform，在 main_demo 里另行挂上。
obstacle_master = false;
if isfield(cfg, 'obstacle')
	obstacle_master = struct_field_default(cfg.obstacle, 'enabled', false);
end
level_constraint.obstacle_enabled = obstacle_master && struct_field_default( ...
	cfg.variance_constraint, [level_prefix, '_obstacle_enabled'], false);
level_constraint.obstacle_points = struct_field_default( ...
	cfg.variance_constraint, [level_prefix, '_obstacle_points'], []);
if level_constraint.obstacle_enabled
	level_constraint.obstacle_centers = cfg.obstacle.centers;
	level_constraint.obstacle_semi_axes = cfg.obstacle.semi_axes;
	level_constraint.obstacle_phi0 = struct_field_default( ...
		cfg.obstacle, 'phi0', 2.0);
	level_constraint.obstacle_phi1_omega = struct_field_default( ...
		cfg.obstacle, 'phi1_omega', 4.0);
	level_constraint.obstacle_slack_enabled = struct_field_default( ...
		cfg.obstacle, 'slack_enabled', true);
	level_constraint.obstacle_slack_weight = struct_field_default( ...
		cfg.obstacle, 'slack_weight', 1e4);
	% 前软后硬切换：复用该层统一的 slack_switch_time（和 hocbf/terminal
	% 相反方向，和 anchor_clf 同方向）。未设置时为 inf，即始终按
	% obstacle_slack_enabled（近似硬）。
	level_constraint.obstacle_slack_hard_after_time = slack_switch_time;
end
end
