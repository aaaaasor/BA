function print_hocbf_diagnostics(hocbf_diag, rollout_elapsed_seconds)
if isempty(hocbf_diag.trace_t)
	return;
end
if nargin < 2
	rollout_elapsed_seconds = nan;
end
disp(['HOCBF max correction norm: ', ...
	num2str(hocbf_diag.max_correction_norm)]);
disp(['HOCBF max uncertainty grad norm: ', ...
	num2str(hocbf_diag.max_grad_norm)]);
disp(['HOCBF max sigma^2: ', ...
	num2str(hocbf_diag.max_sigma2)]);
disp(['HOCBF nominal min barrier b: ', ...
	num2str(hocbf_diag.min_barrier_b)]);
if isfield(hocbf_diag, 'trace_hocbf_enabled') && ...
		~any(logical(hocbf_diag.trace_hocbf_enabled))
	disp('HOCBF disabled.');
else
	disp(['PTCBF/HOCBF min relaxed barrier b: ', ...
		num2str(hocbf_diag.min_relaxed_barrier_b)]);
	disp(['PTCBF/HOCBF min psi1: ', ...
		num2str(hocbf_diag.min_psi1)]);
	if isfinite(hocbf_diag.min_psi1)
		disp(['  min psi1 context: sample ', ...
			num2str(hocbf_diag.min_psi1_sample_idx), ', step ', ...
			num2str(hocbf_diag.min_psi1_step_idx), ', stage ', ...
			hocbf_diag.min_psi1_stage, ', t ', ...
			num2str(hocbf_diag.min_psi1_t)]);
		disp(['  min psi1 terms: sigma2 beta ', ...
			num2str(hocbf_diag.min_psi1_sigma2), ', cumulative ', ...
			num2str(hocbf_diag.min_psi1_cumulative_variance), ...
			', time-average ', ...
			num2str(hocbf_diag.min_psi1_time_average_variance)]);
		disp(['  min psi1 barrier terms: b ', ...
			num2str(hocbf_diag.min_psi1_barrier_b), ', psi0=b+hbar ', ...
			num2str(hocbf_diag.min_psi1_psi0), ', hbar ', ...
			num2str(hocbf_diag.min_psi1_h_bar)]);
		disp(['  min psi1 derivative terms: psi0_dot ', ...
			num2str(hocbf_diag.min_psi1_psi0_dot), ', hbar_dot ', ...
			num2str(hocbf_diag.min_psi1_h_bar_dot), ...
			', alpha0*psi0 ', ...
			num2str(hocbf_diag.min_psi1_alpha_psi0)]);
	end
	disp(['PTCBF/HOCBF min psi2: ', ...
		num2str(hocbf_diag.min_psi2)]);
	disp(['HOCBF max constraint residual: ', ...
		num2str(hocbf_diag.max_hocbf_constraint_residual)]);
	if isfield(hocbf_diag, 'max_hocbf_relaxed_constraint_residual')
		disp(['HOCBF max relaxed residual after QP slack: ', ...
			num2str(hocbf_diag.max_hocbf_relaxed_constraint_residual)]);
	end
	if isfield(hocbf_diag, 'trace_hocbf_slack') && ...
			~isempty(hocbf_diag.trace_hocbf_slack) && ...
			any(isfinite(hocbf_diag.trace_hocbf_slack))
		disp(['HOCBF max slack: ', ...
			num2str(max(hocbf_diag.trace_hocbf_slack))]);
	end
end
if isfinite(hocbf_diag.min_terminal_h)
	disp(['Terminal PTCBF min relaxed barrier hbar-h_T: ', ...
		num2str(hocbf_diag.min_terminal_h)]);
	disp(['  min terminal barrier context: sample ', ...
		num2str(hocbf_diag.min_terminal_h_sample_idx), ', step ', ...
		num2str(hocbf_diag.min_terminal_h_step_idx), ', stage ', ...
		hocbf_diag.min_terminal_h_stage, ', t ', ...
		num2str(hocbf_diag.min_terminal_h_t)]);
	disp(['  min h_T terms: beta ', ...
		num2str(hocbf_diag.min_terminal_h_sigma2), ...
		', h=beta-beta_final ', ...
		num2str(hocbf_diag.min_terminal_h_inequality_h), ...
		', hbar ', ...
		num2str(hocbf_diag.min_terminal_h_ptzf_bound), ...
		', beta_cap ', ...
		num2str(hocbf_diag.min_terminal_h_beta_cap), ...
		', residual ', ...
		num2str(hocbf_diag.min_terminal_h_residual)]);
	disp(['Terminal PTCBF max constraint residual: ', ...
		num2str(hocbf_diag.max_terminal_constraint_residual)]);
	if isfield(hocbf_diag, 'max_terminal_relaxed_constraint_residual')
		disp(['Terminal PTCBF max relaxed residual after QP slack: ', ...
			num2str(hocbf_diag.max_terminal_relaxed_constraint_residual)]);
	end
	if isfield(hocbf_diag, 'trace_terminal_slack') && ...
			~isempty(hocbf_diag.trace_terminal_slack) && ...
			any(isfinite(hocbf_diag.trace_terminal_slack))
		disp(['Terminal PTCBF max slack: ', ...
			num2str(max(hocbf_diag.trace_terminal_slack))]);
	end
	if isfield(hocbf_diag, 'trace_anchor_clf_residual') && ...
			~isempty(hocbf_diag.trace_anchor_clf_residual) && ...
			any(isfinite(hocbf_diag.trace_anchor_clf_residual))
		disp(['Anchor CLF max constraint residual: ', ...
			num2str(max(hocbf_diag.trace_anchor_clf_residual))]);
	end
	if isfield(hocbf_diag, 'trace_anchor_clf_raw_residual') && ...
			~isempty(hocbf_diag.trace_anchor_clf_raw_residual) && ...
			any(isfinite(hocbf_diag.trace_anchor_clf_raw_residual))
		disp(['Anchor CLF max raw residual: ', ...
			num2str(max(hocbf_diag.trace_anchor_clf_raw_residual))]);
	end
	if isfield(hocbf_diag, 'trace_anchor_clf_slack') && ...
			~isempty(hocbf_diag.trace_anchor_clf_slack) && ...
			any(isfinite(hocbf_diag.trace_anchor_clf_slack))
		disp(['Anchor CLF max slack: ', ...
			num2str(max(hocbf_diag.trace_anchor_clf_slack))]);
	end
	if isfield(hocbf_diag, 'trace_qp_slack') && ...
			~isempty(hocbf_diag.trace_qp_slack) && ...
			any(isfinite(hocbf_diag.trace_qp_slack))
		disp(['QP max slack over all constraints: ', ...
			num2str(max(hocbf_diag.trace_qp_slack))]);
	end
	disp(['QP min exitflag: ', num2str(hocbf_diag.min_qp_exitflag), ...
		', max active constraints: ', ...
		num2str(hocbf_diag.max_qp_active_constraint_count)]);
	if isfield(hocbf_diag, 'max_qp_iterations')
		disp(['QP max iterations used (cap 200 unless changed): ', ...
			num2str(hocbf_diag.max_qp_iterations)]);
	end
	if isfield(hocbf_diag, 'total_qp_solve_seconds')
		if isfinite(rollout_elapsed_seconds) && rollout_elapsed_seconds > 0
			disp(['QP total solve time: ', ...
				num2str(hocbf_diag.total_qp_solve_seconds, '%.2f'), ...
				's / rollout total ', ...
				num2str(rollout_elapsed_seconds, '%.2f'), 's (', ...
				num2str(100 * hocbf_diag.total_qp_solve_seconds / ...
				rollout_elapsed_seconds, '%.1f'), '%)']);
		else
			disp(['QP total solve time: ', ...
				num2str(hocbf_diag.total_qp_solve_seconds, '%.2f'), 's']);
		end
	end
end
% 归一化前行范数统计(供 slack 权重重新标定用, w_new = w_old * median(r)^2)。
if isfield(hocbf_diag, 'trace_grad_norm') && ~isempty(hocbf_diag.trace_grad_norm)
	gn = hocbf_diag.trace_grad_norm;
	disp(['HOCBF/terminal grad_x row norm (pre-normalization) median/mean/max: ', ...
		num2str(median(gn), '%.4g'), ' / ', num2str(mean(gn), '%.4g'), ' / ', ...
		num2str(max(gn), '%.4g')]);
end
if isfield(hocbf_diag, 'trace_anchor_clf_grad_norm') && ...
		~isempty(hocbf_diag.trace_anchor_clf_grad_norm) && ...
		any(hocbf_diag.trace_anchor_clf_grad_norm > 0)
	cn = hocbf_diag.trace_anchor_clf_grad_norm(hocbf_diag.trace_anchor_clf_grad_norm > 0);
	disp(['Anchor CLF grad row norm (pre-normalization) median/mean/max: ', ...
		num2str(median(cn), '%.4g'), ' / ', num2str(mean(cn), '%.4g'), ' / ', ...
		num2str(max(cn), '%.4g')]);
end
% 障碍 CBF 诊断(fix 5): 独立打印, 无 OOD 控制时也要能看到。
% min_obstacle_h 是"原始 h"(不含 QP slack), 才是真实安全度量(fix 4)。
if isfield(hocbf_diag, 'trace_u_contribution_hocbf_norm') && ...
		~isempty(hocbf_diag.trace_u_contribution_hocbf_norm)
	disp(['KKT max control contribution norms: HOCBF ', ...
		num2str(max(hocbf_diag.trace_u_contribution_hocbf_norm), '%.4g'), ...
		', terminal ', ...
		num2str(max(hocbf_diag.trace_u_contribution_terminal_norm), '%.4g'), ...
		', anchor PTCLF ', ...
		num2str(max(hocbf_diag.trace_u_contribution_anchor_clf_norm), '%.4g'), ...
		', obstacle PTCBF ', ...
		num2str(max(hocbf_diag.trace_u_contribution_obstacle_norm), '%.4g')]);
	disp(['KKT max u reconstruction error: ', ...
		num2str(max(hocbf_diag.trace_kkt_u_reconstruction_error), '%.4g')]);
end
if isfield(hocbf_diag, 'trace_anchor_clf_first_raw_residual') && ...
		~isempty(hocbf_diag.trace_anchor_clf_first_raw_residual)
	local_print_endpoint_summary(hocbf_diag, 'first', 'P1');
	local_print_endpoint_summary(hocbf_diag, 'last', 'P5');
end
if isfield(hocbf_diag, 'trace_x') && ~isempty(hocbf_diag.trace_x)
	state_norm = sqrt(sum(hocbf_diag.trace_x .^ 2, 2));
	[~, max_state_idx] = max(state_norm);
	local_print_trace_context(hocbf_diag, max_state_idx, ...
		'Maximum state norm context');

	sample_ids = unique(hocbf_diag.trace_sample_idx(:), 'stable');
	initial_state_norm = zeros(size(state_norm));
	for sample_now = sample_ids'
		rows_now = find(hocbf_diag.trace_sample_idx == sample_now);
		initial_state_norm(rows_now) = state_norm(rows_now(1));
	end
	runaway_threshold = 5.0 * max(1.0, initial_state_norm);
	runaway_rows = find(state_norm > runaway_threshold & state_norm > 5.0);
	if ~isempty(runaway_rows)
		runaway_order_data = [hocbf_diag.trace_t(runaway_rows), ...
			hocbf_diag.trace_sample_idx(runaway_rows), ...
			hocbf_diag.trace_step_idx(runaway_rows), ...
			hocbf_diag.trace_stage_idx(runaway_rows)];
		[~, runaway_order] = sortrows(runaway_order_data);
		local_print_trace_context(hocbf_diag, ...
			runaway_rows(runaway_order(1)), ...
			'First runaway candidate (state norm > 5x initial)');
	else
		disp('No state-norm runaway candidate exceeded 5x its sample initial norm.');
	end
end
if isfield(hocbf_diag, 'trace_correction_norm') && ...
		~isempty(hocbf_diag.trace_correction_norm)
	[~, max_control_idx] = max(hocbf_diag.trace_correction_norm);
	local_print_trace_context(hocbf_diag, max_control_idx, ...
		'Maximum QP correction context');
end
if isfield(hocbf_diag, 'obstacle_eval_count') && hocbf_diag.obstacle_eval_count > 0
	disp(['Obstacle CBF min RAW h over rollout (slack-independent): ', ...
		num2str(hocbf_diag.min_obstacle_h), ' at t=', ...
		num2str(hocbf_diag.min_obstacle_h_t), ' (sample ', ...
		num2str(hocbf_diag.min_obstacle_h_sample_idx), ', step ', ...
		num2str(hocbf_diag.min_obstacle_h_step_idx), ')']);
	disp(['Obstacle CBF max slack: ', ...
		num2str(hocbf_diag.max_obstacle_slack)]);
	if hocbf_diag.obstacle_candidate_count > 0
		disp(['Obstacle candidate rows skipped by grad_tol: ', ...
			num2str(hocbf_diag.obstacle_skipped_count), '/', ...
			num2str(hocbf_diag.obstacle_candidate_count), ...
			'; unsafe skipped: ', ...
			num2str(hocbf_diag.obstacle_unsafe_skipped_count), '/', ...
			num2str(hocbf_diag.obstacle_unsafe_count)]);
	end
	disp(['Obstacle CBF activation ratio (sub-steps needing correction): ', ...
		num2str(100 * hocbf_diag.obstacle_active_count / ...
		hocbf_diag.obstacle_eval_count, '%.1f'), '% (', ...
		num2str(hocbf_diag.obstacle_active_count), '/', ...
		num2str(hocbf_diag.obstacle_eval_count), ')']);
	if isfinite(hocbf_diag.obstacle_first_unsafe_t)
		disp(['Obstacle CBF first RAW h<0 at t=', ...
			num2str(hocbf_diag.obstacle_first_unsafe_t), ...
			' (rollout 中途有点进障碍; 最终是否安全看 t=1 曲线评价)']);
	else
		disp('Obstacle CBF: RAW h >= 0 at all evaluated sub-steps.');
	end
	unsafe_rows = find(hocbf_diag.trace_obstacle_h_min < 0 & ...
		isfinite(hocbf_diag.trace_obstacle_h_min));
	if ~isempty(unsafe_rows)
		unsafe_order_data = [hocbf_diag.trace_t(unsafe_rows), ...
			hocbf_diag.trace_sample_idx(unsafe_rows), ...
			hocbf_diag.trace_step_idx(unsafe_rows), ...
			hocbf_diag.trace_stage_idx(unsafe_rows)];
		[~, unsafe_order] = sortrows(unsafe_order_data);
		local_print_obstacle_context(hocbf_diag, ...
			unsafe_rows(unsafe_order(1)), 'First negative obstacle h context');
		local_print_obstacle_context(hocbf_diag, ...
			unsafe_rows(unsafe_order(end)), 'Last negative obstacle h context');
		[~, min_h_trace_idx] = min( ...
			hocbf_diag.trace_obstacle_h_min);
		local_print_obstacle_context(hocbf_diag, min_h_trace_idx, ...
			'Minimum obstacle h context');
	end
end
end

function local_print_trace_context(hocbf_diag, idx, label)
stage_idx = hocbf_diag.trace_stage_idx(idx);
fprintf('\n%s:\n', label);
fprintf('  sample=%d, step=%d, stage=k%d, t=%.8g\n', ...
	hocbf_diag.trace_sample_idx(idx), hocbf_diag.trace_step_idx(idx), ...
	stage_idx, hocbf_diag.trace_t(idx));
x_now = hocbf_diag.trace_x(idx, :);
mu_now = hocbf_diag.trace_mu(idx, :);
u_now = hocbf_diag.trace_u(idx, :);
v_now = hocbf_diag.trace_v(idx, :);
fprintf('  norms: ||x||=%.6g, ||mu||=%.6g, ||u||=%.6g, ||v||=%.6g\n', ...
	norm(x_now), norm(mu_now), norm(u_now), norm(v_now));
fprintf(['  KKT contributions: HOCBF=%.6g, terminal=%.6g, ', ...
	'anchor PTCLF=%.6g, obstacle PTCBF=%.6g\n'], ...
	hocbf_diag.trace_u_contribution_hocbf_norm(idx), ...
	hocbf_diag.trace_u_contribution_terminal_norm(idx), ...
	hocbf_diag.trace_u_contribution_anchor_clf_norm(idx), ...
	hocbf_diag.trace_u_contribution_obstacle_norm(idx));
fprintf(['  HOCBF: psi0=%.6g, psi1=%.6g, psi2=%.6g, ', ...
	'bound=%.6g, slack=%.6g, relaxed residual=%.6g\n'], ...
	hocbf_diag.trace_psi0(idx), hocbf_diag.trace_psi1(idx), ...
	hocbf_diag.trace_psi2(idx), hocbf_diag.trace_integral_bound(idx), ...
	hocbf_diag.trace_hocbf_slack(idx), ...
	hocbf_diag.trace_hocbf_relaxed_constraint_residual(idx));
fprintf(['  PTCLF: g=%.6g, gbar=%.6g, bound=%.6g, ', ...
	'slack=%.6g, residual=%.6g\n'], ...
	hocbf_diag.trace_anchor_clf_v(idx), ...
	hocbf_diag.trace_anchor_clf_ptzf_bound(idx), ...
	hocbf_diag.trace_anchor_clf_bound(idx), ...
	hocbf_diag.trace_anchor_clf_slack(idx), ...
	hocbf_diag.trace_anchor_clf_residual(idx));
if isfield(hocbf_diag, 'trace_anchor_clf_first_raw_residual')
	local_print_endpoint_context(hocbf_diag, idx, 'first', 'P1');
	local_print_endpoint_context(hocbf_diag, idx, 'last', 'P5');
end
fprintf(['  obstacle: h_min=%.6g, slack=%.6g, ', ...
	'max residual without u=%.6g\n'], ...
	hocbf_diag.trace_obstacle_h_min(idx), ...
	hocbf_diag.trace_obstacle_slack(idx), ...
	hocbf_diag.trace_obstacle_max_residual_without_u(idx));
if isfield(hocbf_diag, 'trace_obstacle_min_grad_ctrl_norm')
	fprintf(['  obstacle min-row: point=%g, obstacle=%g, active=%d, ', ...
		'||grad_true||=%.6g, ||grad_ctrl||=%.6g, phi=%.6g\n'], ...
		hocbf_diag.trace_obstacle_min_point_idx(idx), ...
		hocbf_diag.trace_obstacle_min_obstacle_idx(idx), ...
		hocbf_diag.trace_obstacle_min_row_active(idx), ...
		hocbf_diag.trace_obstacle_min_grad_true_norm(idx), ...
		hocbf_diag.trace_obstacle_min_grad_ctrl_norm(idx), ...
		hocbf_diag.trace_obstacle_min_phi(idx));
	fprintf(['  obstacle min-row derivatives: drift=%.6g, ', ...
		'qp control=%.6g, true control=%.6g, ', ...
		'qp hdot=%.6g, true hdot=%.6g\n'], ...
		hocbf_diag.trace_obstacle_min_drift(idx), ...
		hocbf_diag.trace_obstacle_min_qp_control(idx), ...
		hocbf_diag.trace_obstacle_min_true_control(idx), ...
		hocbf_diag.trace_obstacle_min_qp_hdot(idx), ...
		hocbf_diag.trace_obstacle_min_true_hdot(idx));
	fprintf(['  obstacle min-row residuals: qp=%.6g, true=%.6g, ', ...
		'row slack=%.6g, skipped unsafe rows=%g\n'], ...
		hocbf_diag.trace_obstacle_min_qp_residual(idx), ...
		hocbf_diag.trace_obstacle_min_true_residual(idx), ...
		hocbf_diag.trace_obstacle_min_row_slack(idx), ...
		hocbf_diag.trace_obstacle_unsafe_skipped_count(idx));
end
fprintf('  x=%s\n', mat2str(x_now, 5));
fprintf('  mu=%s\n', mat2str(mu_now, 5));
fprintf('  u=%s\n', mat2str(u_now, 5));
fprintf('  v=%s\n', mat2str(v_now, 5));
end

function local_print_endpoint_summary(hocbf_diag, endpoint_name, label)
prefix = ['trace_anchor_clf_', endpoint_name, '_'];
raw = hocbf_diag.([prefix, 'raw_residual']);
relaxed = hocbf_diag.([prefix, 'residual']);
slack = hocbf_diag.([prefix, 'slack']);
grad_norm = hocbf_diag.([prefix, 'grad_norm']);
owner_grad_norm = hocbf_diag.([prefix, 'owner_grad_norm']);
u_norm = hocbf_diag.([prefix, 'u_contribution_norm']);
row_present = logical(hocbf_diag.([prefix, 'row_present']));
raw = raw(isfinite(raw));
relaxed = relaxed(isfinite(relaxed));
slack = slack(isfinite(slack));
grad_norm = grad_norm(isfinite(grad_norm));
owner_grad_norm = owner_grad_norm(isfinite(owner_grad_norm));
u_norm = u_norm(isfinite(u_norm));
if isempty(grad_norm)
	return;
end
fprintf(['%s split PTCLF: max raw/relaxed/slack=%.6g / %.6g / %.6g, ', ...
	'min/median owner grad=%.6g / %.6g, median owner/full ratio=%.6g, ', ...
	'max KKT ||u||=%.6g, ', ...
	'row present=%d/%d\n'], label, finite_max(raw), finite_max(relaxed), ...
	finite_max(slack), min(owner_grad_norm), median(owner_grad_norm), ...
	median(owner_grad_norm ./ max(grad_norm, eps)), finite_max(u_norm), ...
	sum(row_present), numel(row_present));
end

function local_print_endpoint_context(hocbf_diag, idx, endpoint_name, label)
prefix = ['trace_anchor_clf_', endpoint_name, '_'];
fprintf(['  %s split row: g=%.6g, gbar=%.6g, full/effective bound=%.6g / %.6g, ', ...
	'raw=%.6g, relaxed=%.6g, slack=%.6g, full/owner ||grad||=%.6g / %.6g, ', ...
	'KKT ||u||=%.6g, present=%d\n'], label, ...
	local_trace_value(hocbf_diag, [prefix, 'v'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'ptzf_bound'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'bound'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'effective_bound'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'raw_residual'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'residual'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'slack'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'grad_norm'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'owner_grad_norm'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'u_contribution_norm'], idx), ...
	local_trace_value(hocbf_diag, [prefix, 'row_present'], idx));
end

function value = local_trace_value(trace, field_name, idx)
values = trace.(field_name);
value = values(idx);
end

function value = finite_max(values)
if isempty(values)
	value = nan;
else
	value = max(values);
end
end

function local_print_obstacle_context(hocbf_diag, idx, label)
fprintf('\n%s:\n', label);
fprintf(['  sample=%d, step=%d, stage=k%d, t=%.8g, h=%.8g, ', ...
	'point=%g, obstacle=%g\n'], ...
	hocbf_diag.trace_sample_idx(idx), hocbf_diag.trace_step_idx(idx), ...
	hocbf_diag.trace_stage_idx(idx), hocbf_diag.trace_t(idx), ...
	hocbf_diag.trace_obstacle_h_min(idx), ...
	hocbf_diag.trace_obstacle_min_point_idx(idx), ...
	hocbf_diag.trace_obstacle_min_obstacle_idx(idx));
fprintf(['  row active=%d, ||grad_true||=%.8g, ||grad_ctrl||=%.8g, ', ...
	'phi=%.8g, slack=%.8g\n'], ...
	hocbf_diag.trace_obstacle_min_row_active(idx), ...
	hocbf_diag.trace_obstacle_min_grad_true_norm(idx), ...
	hocbf_diag.trace_obstacle_min_grad_ctrl_norm(idx), ...
	hocbf_diag.trace_obstacle_min_phi(idx), ...
	hocbf_diag.trace_obstacle_min_row_slack(idx));
fprintf(['  drift=%.8g, qp control=%.8g, true control=%.8g, ', ...
	'qp hdot=%.8g, true hdot=%.8g\n'], ...
	hocbf_diag.trace_obstacle_min_drift(idx), ...
	hocbf_diag.trace_obstacle_min_qp_control(idx), ...
	hocbf_diag.trace_obstacle_min_true_control(idx), ...
	hocbf_diag.trace_obstacle_min_qp_hdot(idx), ...
	hocbf_diag.trace_obstacle_min_true_hdot(idx));
fprintf(['  qp residual=%.8g, true residual=%.8g, ', ...
	'obstacle KKT norm=%.8g, ||u||=%.8g\n'], ...
	hocbf_diag.trace_obstacle_min_qp_residual(idx), ...
	hocbf_diag.trace_obstacle_min_true_residual(idx), ...
	hocbf_diag.trace_u_contribution_obstacle_norm(idx), ...
	hocbf_diag.trace_correction_norm(idx));
end
