function reports = run_first_level_obstacle_abc_experiments()
% Run the advisor's first-level obstacle experiments A/B/C with one geometry.
% Acceptance is intentionally stronger than waypoint safety: every complete
% polyline segment is checked analytically against the ellipse.  The run
% fails unless all three experiments have exactly zero crossing segments.

variants = struct( ...
    'name',  {'A', 'B', 'C'}, ...
    'hocbf', {false, false, true}, ...
    'ptcbf', {false, true, false}, ...
    'obstacle_slack', {false, true, true}, ...
    'cache', { ...
        'LoG_GP_FirstLevel_Rollout_A_ObstacleOnly_NearP3.mat', ...
        'LoG_GP_FirstLevel_Rollout_B_ObstaclePlusVariancePTCBF_NearP3.mat', ...
        'LoG_GP_FirstLevel_Rollout_C_ObstaclePlusVarianceHOCBF_NearP3.mat'});

reports = repmat(struct( ...
    'name', '', 'cache', '', 'discrete_h_min', nan, ...
    'continuous_h_min', nan, 'n_crossing_samples', 0, ...
    'n_crossing_segments', 0), 1, numel(variants));
for k = 1:numel(variants)
    reports(k) = run_one_variant(variants(k));
end

fprintf('\n========== NearP3 A/B/C continuous-safety audit ==========\n');
fprintf('%-4s %14s %16s %18s %18s\n', ...
    'exp', 'discrete hmin', 'continuous hmin', ...
    'crossing samples', 'crossing segments');
for k = 1:numel(reports)
    fprintf('%-4s %14.6g %16.6g %18d %18d\n', ...
        reports(k).name, reports(k).discrete_h_min, ...
        reports(k).continuous_h_min, reports(k).n_crossing_samples, ...
        reports(k).n_crossing_segments);
end

failed = [reports.discrete_h_min] < 0 | ...
    [reports.continuous_h_min] < 0 | ...
    [reports.n_crossing_samples] ~= 0 | ...
    [reports.n_crossing_segments] ~= 0;
if any(failed)
    error('NearP3Safety:CrossingDetected', ...
        'Experiments with a detected obstacle crossing: %s', ...
        strjoin({reports(failed).name}, ', '));
end

report_path = fullfile(fileparts(mfilename('fullpath')), 'outputs', ...
    'LoG_GP_FirstLevel_NearP3_ABC_SafetyReport.mat');
save(report_path, 'reports');
fprintf('PASS: A/B/C all have zero continuous obstacle crossings.\n');
fprintf('Saved safety report: %s\n', report_path);
end

function report = run_one_variant(variant)
cfg_external = get_config();
cfg_external.stop_after_first_level = true;
cfg_external.animation.enabled = false;
cfg_external.output.enabled = false;

% One visible obstacle near the first-level generated waypoint-3 cluster.
cfg_external.obstacle.enabled = true;
cfg_external.obstacle.centers = [0.485; 0.505];
cfg_external.obstacle.semi_axes = [0.04; 0.06];
cfg_external.obstacle.slack_enabled = variant.obstacle_slack;

cfg_external.variance_constraint.first_level_obstacle_enabled = true;
cfg_external.variance_constraint.first_level_obstacle_points = 1:5;
cfg_external.variance_constraint.first_level_hocbf_enabled = variant.hocbf;
cfg_external.variance_constraint.first_level_ptcbf_enabled = variant.ptcbf;
cfg_external.variance_constraint.first_level_ptclf_enabled = false;
cfg_external.cache.first_level_rollout_path = ...
    fullfile('outputs', variant.cache);

fprintf('\n===== Experiment %s: obstacle=%d, variance HOCBF=%d, variance PTCBF=%d =====\n', ...
    variant.name, true, variant.hocbf, variant.ptcbf);
main_demo;

safety = evaluate_trajectory_obstacle_safety( ...
    reconstructed_points, cfg_external.obstacle);
report = struct( ...
    'name', variant.name, ...
    'cache', variant.cache, ...
    'discrete_h_min', safety.discrete_h_min, ...
    'continuous_h_min', safety.continuous_h_min, ...
    'n_crossing_samples', safety.n_crossing_samples, ...
    'n_crossing_segments', safety.n_crossing_segments);
end
